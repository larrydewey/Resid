#!/usr/bin/env python3
"""Generate lib/keccakg.resid: Keccak-f[1600] and the SHA-3 / SHAKE
sponges (FIPS 202), generic over lib/word.resid's Word64(W, B).

The state is a record of 25 lanes (a secret 64-bit word may not live in
a list, E0258); the round is written out lane by lane, so no lane is
chosen by an index at run time.

    python3 tools/gen_keccak.py > lib/keccakg.resid
"""

RC = [
    0x0000000000000001, 0x0000000000008082, 0x800000000000808A, 0x8000000080008000,
    0x000000000000808B, 0x0000000080000001, 0x8000000080008081, 0x8000000000008009,
    0x000000000000008A, 0x0000000000000088, 0x0000000080008009, 0x000000008000000A,
    0x000000008000808B, 0x800000000000008B, 0x8000000000008089, 0x8000000000008003,
    0x8000000000008002, 0x8000000000000080, 0x000000000000800A, 0x800000008000000A,
    0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008,
]

# Rotation offsets r[x][y] (FIPS 202 Table 2), lane index x + 5y.
ROT = [[0, 36, 3, 41, 18], [1, 44, 10, 45, 2], [62, 6, 43, 15, 61], [28, 55, 25, 21, 56], [27, 20, 39, 8, 14]]


def lane(x, y):
    return x + 5 * y


def rotl(expr, n):
    n %= 64
    return expr if n == 0 else f"d_rotr({expr}, {64 - n})"


out = []
w = out.append
w("// keccakg.resid — Keccak-f[1600], SHA3-256, SHA3-512, SHAKE128 and SHAKE256")
w("// (FIPS 202), generic over 64-bit words (lib/word.resid's Word64(W, B)): one")
w("// implementation for public bytes (W = UInt(64), B = Int) and secret bytes")
w("// (Secret(UInt(64)), Secret(UInt(8))). Generated by tools/gen_keccak.py; edit")
w("// that, not this. Lanes are little-endian; lengths are public.")
w("")
w('import "word.resid";')
w("")
fields = "; ".join(f"W a{i}" for i in range(25))
w("/// The Keccak-f[1600] state: 25 lanes, lane x + 5y in field a(x + 5y).")
w(f"type K25(W) = {{ {fields}; }};")
w("")
w("/// The 24 round constants of Keccak-f[1600] (FIPS 202 §3.2.5).")
w("pub List(UInt(64)) keccak_rc() {")
w("    return [" + ", ".join(f"(UInt(64)) {c}" for c in RC) + "];")
w("}")
w("")
w("@needs(Word64(W, B))")
w("K25(W) kc_zero() {")
w("    W z = d_lift((UInt(64)) 0);")
w("    return K25 {" + ", ".join(f".a{i} = z" for i in range(25)) + "};")
w("}")
w("")
w("// One round: theta, rho and pi, chi, iota.")
w("@needs(Word64(W, B))")
w("K25(W) kc_round(K25(W) s, UInt(64) rc) {")
for x in range(5):
    w(f"    W c{x} = d_xor(d_xor(d_xor(d_xor(s.a{lane(x,0)}, s.a{lane(x,1)}), s.a{lane(x,2)}), s.a{lane(x,3)}), s.a{lane(x,4)});")
for x in range(5):
    w(f"    W e{x} = d_xor(c{(x - 1) % 5}, {rotl(f'c{(x + 1) % 5}', 1)});")
# theta then rho+pi: B[y][2x+3y] = rot(A[x][y] ^ D[x], r[x][y])
b = {}
for x in range(5):
    for y in range(5):
        nx, ny = y, (2 * x + 3 * y) % 5
        b[(nx, ny)] = rotl(f"d_xor(s.a{lane(x, y)}, e{x})", ROT[x][y])
for y in range(5):
    for x in range(5):
        w(f"    W b{lane(x, y)} = {b[(x, y)]};")
w("    W rk = d_lift(rc);")
fs = []
for y in range(5):
    for x in range(5):
        e = f"d_xor(b{lane(x, y)}, d_and(d_not(b{lane((x + 1) % 5, y)}), b{lane((x + 2) % 5, y)}))"
        if x == 0 and y == 0:
            e = f"d_xor({e}, rk)"
        fs.append(f".a{lane(x, y)} = {e}")
w("    return K25 {" + ", ".join(fs) + "};")
w("}")
w("")
w("/// Keccak-f[1600]: 24 rounds.")
w("@needs(Word64(W, B))")
w("K25(W) keccak_f(K25(W) s) { return kc_rounds(s, keccak_rc(), 0); }")
w("")
w("@needs(Word64(W, B))")
w("K25(W) kc_rounds(K25(W) s, List(UInt(64)) rc, Int i) {")
w("    if (i >= 24) { return s; }")
w("    return kc_rounds(kc_round(s, rc[i]), rc, i + 1);")
w("}")
w("")
w("// The little-endian lane of bytes m[off .. off + 8].")
w("@needs(Word64(W, B))")
w("W kc_lane_in(List(B) m, Int off) {")
parts = [f"d_from_byte(m[off])"] + [rotl(f"d_from_byte(m[off + {k}])", 8 * k) for k in range(1, 8)]
e = parts[0]
for p in parts[1:]:
    e = f"d_xor({e}, {p})"
w(f"    return {e};")
w("}")
w("")
w("// The block m[off .. off + rate] xored into the first rate/8 lanes.")
w("@needs(Word64(W, B))")
w("K25(W) kc_xor_block(K25(W) s, List(B) m, Int off, Int rate) {")
fs = []
for j in range(25):
    fs.append(f".a{j} = if (rate > {8 * j}) {{ d_xor(s.a{j}, kc_lane_in(m, off + {8 * j})) }} else {{ s.a{j} }}")
w("    return K25 {" + ", ".join(fs) + "};")
w("}")
w("")
w("// Lane j of the state (j public, 0 <= j < 25).")
w("@needs(Word64(W, B))")
w("W kc_lane(K25(W) s, Int j) {")
chain = "s.a24"
for j in range(23, -1, -1):
    chain = f"if (j == {j}) {{ s.a{j} }} else {{ {chain} }}"
w(f"    return {chain};")
w("}")
w("")
w("""// The padded message: pad10*1 with the domain bits `ds` (0x06 for SHA-3,
// 0x1F for SHAKE), as bytes of type B.
@needs(Word64(W, B))
List(B) kc_pad(List(B) m, Int rate, Int ds) {
    Int q = rate - (m.len() % rate);
    List(Int) tail = if (q == 1) { [ds | 128] } else { [ds].concat(kc_zeros(q - 2, [])).concat([128]) };
    ListBuf(B) lb = ListBuf();
    return m.concat(kc_lift(tail, 0, lb));
}

List(Int) kc_zeros(Int n, List(Int) acc) { if (n <= 0) { return acc; } return kc_zeros(n - 1, acc.concat([0])); }

@needs(Word64(W, B))
List(B) kc_lift(List(Int) bs, Int i, ListBuf(B) acc) {
    if (i >= bs.len()) { return acc.finish(); }
    W wv = d_lift(wrapping_u64(bs[i]));
    return kc_lift(bs, i + 1, acc.push(d_byte(wv, 0)));
}

@needs(Word64(W, B))
K25(W) kc_absorb(K25(W) s, List(B) p, Int off, Int rate) {
    if (off >= p.len()) { return s; }
    return kc_absorb(keccak_f(kc_xor_block(s, p, off, rate)), p, off + rate, rate);
}

// n bytes squeezed from s (already permuted after absorbing).
@needs(Word64(W, B))
List(B) kc_squeeze(K25(W) s, Int rate, Int n, Int i, Int at, ListBuf(B) acc) {
    if (i >= n) { return acc.finish(); }
    if (at >= rate) { return kc_squeeze(keccak_f(s), rate, n, i, 0, acc); }
    B byte = d_byte(kc_lane(s, at / 8), (at % 8) * 8);
    return kc_squeeze(s, rate, n, i + 1, at + 1, acc.push(byte));
}

@needs(Word64(W, B))
List(B) kc_sponge(List(B) m, Int rate, Int ds, Int n) {
    K25(W) s = kc_absorb(kc_zero(), kc_pad(m, rate, ds), 0, rate);
    ListBuf(B) out = ListBuf();
    return kc_squeeze(s, rate, n, 0, 0, out);
}

/// SHA3-256 of `msg`: 32 bytes. Secret bytes in give a secret digest.
@needs(Word64(W, B))
@key_from(msg)
pub List(B) sha3_256g(List(B) msg) { return kc_sponge(msg, 136, 6, 32); }

/// SHA3-512 of `msg`: 64 bytes. Secret bytes in give a secret digest.
@needs(Word64(W, B))
@key_from(msg)
pub List(B) sha3_512g(List(B) msg) { return kc_sponge(msg, 72, 6, 64); }

/// SHAKE128 of `msg`, `n` bytes of output (n public).
@needs(Word64(W, B))
@key_from(msg)
pub List(B) shake128g(List(B) msg, Int n) { return kc_sponge(msg, 168, 31, n); }

/// SHAKE256 of `msg`, `n` bytes of output (n public).
@needs(Word64(W, B))
@key_from(msg)
pub List(B) shake256g(List(B) msg, Int n) { return kc_sponge(msg, 136, 31, n); }""")
print("\n".join(out))
