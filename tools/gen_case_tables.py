def simple_maps():
    """(upper_to_lower, lower_to_upper) sorted lists of (from, to)."""
    lower, upper = [], []
    for cp in range(0x110000):
        ch = chr(cp)
        lo = ch.lower()
        up = ch.upper()
        # Single-codepoint simple mapping only; multi-character
        # expansions live in SPECIAL_UPPER.
        if len(lo) == 1 and lo != ch:
            lower.append((cp, ord(lo)))
        if len(up) == 1 and up != ch:
            upper.append((cp, ord(up)))
    return lower, upper


def emit(rows, name):
    out = [f"static const uint32_t {name}[] = {{"]
    for i in range(0, len(rows), 4):
        chunk = ", ".join(f"0x{a:04X},0x{b:04X}" for a, b in rows[i : i + 4])
        out.append(f"    {chunk},")
    out.append("};")
    out.append(f"#define {name}_N {len(rows)}  /* pairs */")
    return "\n".join(out)


def emit_special():
    rows = sorted(SPECIAL_UPPER.items())
    out = ["static const struct { uint32_t cp; const char* up; } SPECIAL_UPPER[] = {"]
    for cp, s in rows:
        lit = "".join(f"\\x{b:02X}" for b in s.encode("utf-8"))
        # Escape sequences must not swallow a following hex digit.
        lit = lit.replace("\\x", "\\x")  # keep readable; C concats adjacent
        parts = []
        for i in range(0, len(lit), 4):
            parts.append(lit[i : i + 4])
        c_lit = '"' + '""'.join(parts) + '"'
        out.append(f"    {{0x{cp:04X}, {c_lit}}},")
    out.append("};")
    out.append(f"#define SPECIAL_UPPER_N {len(rows)}")
    return "\n".join(out)


def main():
    lower, upper = simple_maps()
    with open(RT) as f:
        src = f.read()
    bi = src.index(BEGIN)
    ei = src.index(END) + len(END)
    block = (
        f"{BEGIN}\n"
        f"/* lower: {len(lower)} pairs, upper: {len(upper)} pairs, "
        f"special-upper: {len(SPECIAL_UPPER)} expansions. */\n"
        f"{emit(lower, 'CASE_TO_LOWER')}\n\n"
        f"{emit(upper, 'CASE_TO_UPPER')}\n\n"
        f"{emit_special()}\n"
        f"{END}"
    )
    open(RT, "w").write(src[:bi] + block + src[ei:])
    print(
        f"wrote {RT}: {len(lower)} lower pairs, {len(upper)} upper pairs, "
        f"{len(SPECIAL_UPPER)} special-upper expansions"
    )


if __name__ == "__main__":
    sys.exit(main())
