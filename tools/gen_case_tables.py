"""Generate Unicode case-mapping tables into crates/residc/resid_rt.c.

Extracts every codepoint whose simple lowercase/uppercase mapping (per
Python's unicodedata, which mirrors UnicodeData.txt) is a single differing
codepoint, and writes two sorted uint32 pair tables between
BEGIN/END CASE TABLES markers in resid_rt.c. `resid_case_simple` binary-
searches them after the algorithmic ranges.

Also emits SPECIAL_UPPER: the unconditional multi-character uppercase
expansions from Unicode SpecialCasing.txt (ß→SS, ligatures, ŉ→ʼN, the
Greek ypogegrammeni forms, ...), consulted before the simple table.
Conditional rules handled directly in the runtime: Final_Sigma (Σ→ς
word-finally) in str_to_lower.

Run from the repo root:  python3 tools/gen_case_tables.py
"""
