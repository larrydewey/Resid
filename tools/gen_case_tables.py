#!/usr/bin/env python3
"""Generate Unicode case-mapping tables as runtime/rt/case_tables.resid.

Extracts every codepoint whose simple lowercase/uppercase mapping (per
Python's unicodedata, which mirrors UnicodeData.txt) is a single differing
codepoint, and writes two sorted (from, to) pair tables as resid_raw_table
data; runtime/rt/case.resid binary-searches them.

Also emits the special-upper table: the unconditional multi-character uppercase
expansions from Unicode SpecialCasing.txt (ß→SS, ligatures, ŉ→ʼN, the
Greek ypogegrammeni forms, ...), consulted before the simple table.
Conditional rules handled directly in the runtime: Final_Sigma (Σ→ς
word-finally) in str_to_lower.

Run from the repo root:  python3 tools/gen_case_tables.py
"""
import sys
import unicodedata

OUT = "runtime/rt/case_tables.resid"

def special_upper():
    """The unconditional SpecialCasing uppercase expansions: every codepoint
    whose full uppercase (Python's str.upper, which applies SpecialCasing.txt's
    locale-independent entries) is more than one codepoint."""
    out = {}
    for cp in range(0x110000):
        up = chr(cp).upper()
        if len(up) > 1:
            out[cp] = up
    return out


def simple_maps():
    """(upper_to_lower, lower_to_upper) sorted lists of (from, to)."""
    lower, upper = [], []
    for cp in range(0x110000):
        ch = chr(cp)
        lo = ch.lower()
        up = ch.upper()
        # Single-codepoint simple mapping only; multi-character
        # expansions live in special_upper().
        if len(lo) == 1 and lo != ch:
            lower.append((cp, ord(lo)))
        if len(up) == 1 and up != ch:
            upper.append((cp, ord(up)))
    return lower, upper


def table(name, values):
    lines = []
    for i in range(0, len(values), 8):
        lines.append("        " + ", ".join(values[i : i + 8]))
    return f"pub Int {name}() {{\n    return resid_raw_table([\n" + ",\n".join(lines) + "\n    ]);\n}\n"


def main():
    lower, upper = simple_maps()
    special = sorted(special_upper().items())
    # A special entry: codepoint, byte count, then 9 byte slots.
    spec = []
    for cp, text in special:
        b = list(text.encode("utf-8"))
        assert len(b) <= 9
        spec.append(", ".join([f"0x{cp:04X}", str(len(b))] + [str(x) for x in b + [0] * (9 - len(b))]))
    out = [
        "// Unicode case-mapping tables, generated by tools/gen_case_tables.py;",
        f"// do not edit. lower: {len(lower)} pairs, upper: {len(upper)} pairs,",
        f"// special-upper: {len(special)} expansions (codepoint, byte count, 9 byte slots).",
        "",
        table("case_lower_tab", [f"0x{a:04X}, 0x{b:04X}" for a, b in lower]),
        f"pub Int case_lower_n() {{ return {len(lower)}; }}\n",
        table("case_upper_tab", [f"0x{a:04X}, 0x{b:04X}" for a, b in upper]),
        f"pub Int case_upper_n() {{ return {len(upper)}; }}\n",
        table("case_special_tab", spec),
        f"pub Int case_special_n() {{ return {len(special)}; }}",
    ]
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {OUT}: {len(lower)} lower pairs, {len(upper)} upper pairs, {len(special)} special-upper expansions")


if __name__ == "__main__":
    sys.exit(main())
