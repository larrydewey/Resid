#!/usr/bin/env python3
"""Generate tests/crypto/aead_test.resid: AES-GCM and ChaCha20-Poly1305
(lib/aesgcmg.resid, lib/chachag.resid) against pyca/cryptography (OpenSSL)
and RFC 8439's appendix A, at public and secret types, on the AES-NI /
carry-less multiply path and the software path, and through the packed
(List(UInt(8))) entry points.

Lengths straddle the 16-byte block and the 64-byte four-block step (0, 1,
15, 16, 17, 63, 64, 65, 255, 4096, 32768 + 13), with associated data that
is not a multiple of the block, and IVs of 12 bytes and of other lengths.
Inputs of 255 bytes or less are written out; longer ones are made in the
test by pat(n, k) (byte i is (i * 131 + k * 7 + i / 256) mod 256) and the
result compared by its SHA-256.

Usage: tools/gen_aead_ref.py [--check]   (--check: verify the RFC vectors
against pyca and that the committed file is current, write nothing)
"""
import hashlib
import sys
from pathlib import Path

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms
from cryptography.hazmat.primitives.ciphers.aead import AESGCM, ChaCha20Poly1305
from cryptography.hazmat.primitives.poly1305 import Poly1305

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "crypto" / "aead_test.resid"

RFC = {}
exec((Path(__file__).resolve().parent / "aead_rfc8439.py").read_text(), RFC)


def pat(n, k):
    return bytes(((i * 131 + k * 7 + i // 256) & 255) for i in range(n))


def chacha20(key, counter, nonce, data):
    c = Cipher(algorithms.ChaCha20(key, counter.to_bytes(4, "little") + nonce), mode=None).encryptor()
    return c.update(data)


def lit(b):
    return "[" + ", ".join(str(x) for x in b) + "]"


def data_expr(b, n, k):
    """The Resid expression for input bytes: a literal, or pat(n, k)."""
    return f"rt {lit(b)}" if n <= 255 else f"pat({n}, {k})"


def want_expr(out):
    return f'"{out.hex()}"' if len(out) <= 271 else f'"sha256:{hashlib.sha256(out).hexdigest()}"'


def check_rfc():
    for key, nonce, ctr, ks in RFC["A1"]:
        assert chacha20(bytes.fromhex(key), ctr, bytes.fromhex(nonce), bytes(64)).hex() == ks
    for key, nonce, ctr, pt, ct in RFC["A2"]:
        assert chacha20(bytes.fromhex(key), ctr, bytes.fromhex(nonce), bytes.fromhex(pt)).hex() == ct
    for k, m, tag in RFC["A3_DUMP"] + RFC["A3_ROWS"]:
        assert Poly1305.generate_tag(bytes.fromhex(k), bytes.fromhex(m)).hex() == tag
    key, nonce, aad, ct, tag, pt = RFC["A5"]
    assert ChaCha20Poly1305(bytes.fromhex(key)).decrypt(bytes.fromhex(nonce), bytes.fromhex(ct + tag), bytes.fromhex(aad)).hex() == pt


HEAD = '''// GENERATED by tools/gen_aead_ref.py; do not edit.
// AES-GCM and ChaCha20-Poly1305 (lib/aesgcmg.resid, lib/chachag.resid)
// against pyca/cryptography and RFC 8439 appendix A: every vector at
// public and secret types, on AES-NI / carry-less multiply (where the CPU
// has them) and in software, and through the packed entry points
// (aes_gcmg_seal_u8 / aes_gcmg_decrypt_u8 and the ChaCha20-Poly1305 *_u8
// functions). Lengths straddle the block and the four-block step; long
// inputs come from pat(n, k) and are compared by their SHA-256.

import "../../lib/aesgcmg.resid";
import "../../lib/aesgcm.resid";
import "../../lib/chachag.resid";
import "../../lib/chacha.resid";
import "../../lib/word.resid";
import "../../lib/crypto.resid";

List(Int) pat(Int n, Int k) { return pat_at(n, k, 0, ListBuf()); }

List(Int) pat_at(Int n, Int k, Int i, ListBuf(Int) acc) {
    if (i >= n) { return acc.finish(); }
    return pat_at(n, k, i + 1, acc.push((i * 131 + k * 7 + i / 256) & 255));
}

// Short outputs as hex, long ones as the hex of their SHA-256.
Str shown(List(Int) b) { return if (b.len() <= 271) { hex_encode(b) } else { "sha256:" + hex_encode(sha256_bytes(b)) }; }

@requires(declassify)
List(Int) opened(List(Secret(UInt(8))) b) { return bytes_int(declassify(secret_join(b), "test compares to the reference")); }

@requires(declassify)
Str sshown(List(Secret(UInt(8))) b) { return shown(opened(b)); }

Str pick(Str acc, Bool ok, Str name) { return if (acc != "") { acc } else if (ok) { "" } else { name }; }

List(Int) flip_last(List(Int) b) { return b[0..b.len() - 1].concat([b[b.len() - 1] ^ 1]); }

Str opt_shown(Option(List(Int)) o) { return match o { Some(p) => shown(p), None => "none" }; }

@requires(declassify)
Str sopt_shown(Option(List(Secret(UInt(8)))) o) { return match o { Some(p) => sshown(p), None => "none" }; }

// AES-GCM every way: "" when all agree with want (ct || tag, shown), else
// the first that does not.
@requires(declassify)
Str gcm_all(List(Int) key, List(Int) iv, List(Int) pt, List(Int) aad, Str want) {
    Bool hw = resid_cpu_has_aesni();
    Bool cl = resid_cpu_has_clmul();
    List(Secret(UInt(8))) sk = secret_bytes(key);
    List(Secret(UInt(8))) sp = secret_bytes(pt);
    List(Int) ct = aes_gcm_seal(key, iv, pt, aad);
    Str p = shown(pt);
    Str a1 = pick("", shown(ct) == want, "public api seal");
    Str a2 = pick(a1, shown(aes_gcmg_seal_with(false, false, key, iv, pt, aad)) == want, "public sw seal");
    Str a3 = pick(a2, shown(aes_gcmg_seal_with(hw, cl, key, iv, pt, aad)) == want, "public hw seal");
    Str a4 = pick(a3, sshown(aes_gcmg_seal_with(false, false, sk, iv, sp, aad)) == want, "secret sw seal");
    Str a5 = pick(a4, sshown(aes_gcmg_seal_with(hw, cl, sk, iv, sp, aad)) == want, "secret hw seal");
    Str a6 = pick(a5, sshown(aes_gcmg_seal_u8(sk, iv, bytes_u8(pt), aad)) == want, "secret u8 seal");
    Str a6b = pick(a6, sshown(aes_gcmg_seal_with(hw, false, sk, iv, sp, aad)) == want && sshown(aes_gcmg_seal_with(false, cl, sk, iv, sp, aad)) == want, "secret mixed seal");
    Str b1 = pick(a6b, opt_shown(aes_gcm_decrypt(key, iv, ct, aad)) == p, "public api open");
    Str b2 = pick(b1, opt_shown(aes_gcmg_decrypt_with(false, false, key, iv, ct, aad)) == p, "public sw open");
    Str b3 = pick(b2, sopt_shown(aes_gcmg_decrypt_with(false, false, sk, iv, ct, aad)) == p, "secret sw open");
    Str b4 = pick(b3, sopt_shown(aes_gcmg_decrypt_with(hw, cl, sk, iv, ct, aad)) == p, "secret hw open");
    Str b5 = pick(b4, sopt_shown(aes_gcmg_decrypt_u8_with(false, false, sk, iv, bytes_u8(ct), aad)) == p, "secret u8 sw open");
    Str b6 = pick(b5, sopt_shown(aes_gcmg_decrypt_u8(sk, iv, bytes_u8(ct), aad)) == p, "secret u8 open");
    Str b7 = pick(b6, opt_shown(aes_gcmg_decrypt_u8_with(hw, cl, key, iv, bytes_u8(ct), aad)) == p, "public u8 open");
    List(Int) bad = flip_last(ct);
    Str c1 = pick(b7, sopt_shown(aes_gcmg_decrypt_with(false, false, sk, iv, bad, aad)) == "none" && sopt_shown(aes_gcmg_decrypt(sk, iv, bad, aad)) == "none", "tampered tag accepted");
    List(Int) badc = if (ct.len() > 16) { [ct[0] ^ 128].concat(ct[1..]) } else { bad };
    return pick(c1, sopt_shown(aes_gcmg_decrypt_u8(sk, iv, bytes_u8(badc), aad)) == "none" && opt_shown(aes_gcm_decrypt(key, iv, badc, aad)) == "none", "tampered ciphertext accepted");
}

// ChaCha20-Poly1305 every way, as gcm_all.
@requires(declassify)
Str cc_all(List(Int) key, List(Int) nonce, List(Int) pt, List(Int) aad, Str want) {
    List(Secret(UInt(8))) sk = secret_bytes(key);
    List(Secret(UInt(8))) sp = secret_bytes(pt);
    List(Int) ct = chacha20poly1305_seal(key, nonce, pt, aad);
    Str p = shown(pt);
    Str a1 = pick("", shown(ct) == want, "public api seal");
    Str a2 = pick(a1, sshown(chacha20poly1305g_seal(sk, nonce, sp, aad)) == want, "secret seal");
    Str a3 = pick(a2, sshown(chacha20poly1305g_seal_nb(sk, secret_bytes(nonce), sp, aad)) == want, "secret nonce seal");
    Str a4 = pick(a3, sshown(chacha20poly1305g_seal_u8(sk, nonce, bytes_u8(pt), aad)) == want, "secret u8 seal");
    Str b1 = pick(a4, opt_shown(chacha20poly1305_decrypt(key, nonce, ct, aad)) == p, "public api open");
    Str b2 = pick(b1, sopt_shown(chacha20poly1305g_decrypt(sk, nonce, ct, aad)) == p, "secret open");
    Str b3 = pick(b2, sopt_shown(chacha20poly1305g_decrypt_nb(sk, secret_bytes(nonce), ct, aad)) == p, "secret nonce open");
    Str b4 = pick(b3, sopt_shown(chacha20poly1305g_decrypt_u8(sk, nonce, bytes_u8(ct), aad)) == p, "secret u8 open");
    Str b5 = pick(b4, opt_shown(chacha20poly1305g_decrypt_u8(key, nonce, bytes_u8(ct), aad)) == p, "public u8 open");
    List(Int) bad = flip_last(ct);
    Str c1 = pick(b5, sopt_shown(chacha20poly1305g_decrypt(sk, nonce, bad, aad)) == "none" && opt_shown(chacha20poly1305_decrypt(key, nonce, bad, aad)) == "none", "tampered tag accepted");
    List(Int) badc = if (ct.len() > 16) { [ct[0] ^ 128].concat(ct[1..]) } else { bad };
    return pick(c1, sopt_shown(chacha20poly1305g_decrypt_u8(sk, nonce, bytes_u8(badc), aad)) == "none", "tampered ciphertext accepted");
}

// The ChaCha20 keystream XOR every way.
@requires(declassify)
Str xor_all(List(Int) key, Int ctr, List(Int) nonce, List(Int) data, Str want) {
    List(Secret(UInt(8))) sk = secret_bytes(key);
    Str a1 = pick("", shown(chacha20_xor(key, ctr, nonce, data)) == want, "public xor");
    Str a2 = pick(a1, sshown(chachag_xor(sk, ctr, nonce, secret_bytes(data))) == want, "secret xor");
    return pick(a2, sshown(chachag_xor_u8(sk, ctr, nonce, bytes_u8(data))) == want, "secret u8 xor");
}

// Poly1305 every way.
@requires(declassify)
Str poly_all(List(Int) key, List(Int) msg, Str want) {
    List(Secret(UInt(8))) sk = secret_bytes(key);
    Str a1 = pick("", shown(poly1305(key, msg)) == want, "public poly1305");
    Str a2 = pick(a1, sshown(poly1305g(sk, secret_bytes(msg))) == want, "secret poly1305");
    return pick(a2, sshown(poly1305g_u8(sk, bytes_u8(msg))) == want, "secret u8 poly1305");
}
'''


def main():
    check_rfc()
    out = [HEAD]
    n_tests = 0

    def test(name, body):
        nonlocal n_tests
        n_tests += 1
        out.append(f'@requires(declassify)\ntest "{name}" {{\n{body}\n}}\n')

    # RFC 8439 A.1 / A.4: keystream blocks; A.2: encryption; A.3: Poly1305; A.5: AEAD.
    for i, (key, nonce, ctr, ks) in enumerate(RFC["A1"]):
        test(f"rfc8439 A.1 #{i + 1} chacha20 block",
             f'    List(Int) key = rt {lit(bytes.fromhex(key))};\n'
             f'    expect(hex_encode(chacha_block(key, {ctr}, {lit(bytes.fromhex(nonce))}))).toEqual("{ks}");\n'
             f'    expect(hex_encode(opened(chachag_block(secret_bytes(key), {ctr}, {lit(bytes.fromhex(nonce))})))).toEqual("{ks}");')
    for i, (key, nonce, ctr, pt, ct) in enumerate(RFC["A2"]):
        test(f"rfc8439 A.2 #{i + 1} chacha20 encryption",
             f'    expect(xor_all(rt {lit(bytes.fromhex(key))}, {ctr}, {lit(bytes.fromhex(nonce))}, rt {lit(bytes.fromhex(pt))}, {want_expr(bytes.fromhex(ct))})).toEqual("");')
    for i, (k, m, tag) in enumerate(RFC["A3_DUMP"] + RFC["A3_ROWS"]):
        test(f"rfc8439 A.3 #{i + 1} poly1305",
             f'    expect(poly_all(rt {lit(bytes.fromhex(k))}, rt {lit(bytes.fromhex(m))}, "{tag}")).toEqual("");')
    key, nonce, aad, ct, tag, pt = RFC["A5"]
    test("rfc8439 A.5 aead decryption",
         f'    expect(cc_all(rt {lit(bytes.fromhex(key))}, {lit(bytes.fromhex(nonce))}, rt {lit(bytes.fromhex(pt))}, {lit(bytes.fromhex(aad))}, {want_expr(bytes.fromhex(ct + tag))})).toEqual("");')

    # Lengths around the block (16) and the four-block step (64).
    lens = [0, 1, 15, 16, 17, 63, 64, 65, 255, 4096, 32768 + 13]
    aads = [0, 13, 20, 1, 16, 33, 0, 5, 12, 31, 4]
    k = 0
    for ksz in (16, 24, 32):
        for j, n in enumerate(lens):
            k += 1
            key = pat(ksz, 100 + k)
            iv = pat(12, 200 + k)
            pt = pat(n, k)
            aad = pat(aads[j], 300 + k)
            out_ = AESGCM(key).encrypt(iv, pt, aad)
            test(f"aes{ksz * 8}-gcm pt {n} aad {len(aad)}",
                 f'    expect(gcm_all(rt {lit(key)}, {lit(iv)}, {data_expr(pt, n, k)}, {lit(aad)}, {want_expr(out_)})).toEqual("");')
    # IVs other than 96 bits (J0 is a GHASH of the IV).
    for ivlen, n in ((8, 33), (16, 64), (60, 100), (13, 4096)):
        k += 1
        key = pat(16 if ivlen != 13 else 32, 100 + k)
        iv = pat(ivlen, 200 + k)
        pt = pat(n, k)
        aad = pat(7, 300 + k)
        out_ = AESGCM(key).encrypt(iv, pt, aad)
        test(f"aes{len(key) * 8}-gcm iv {ivlen} pt {n}",
             f'    expect(gcm_all(rt {lit(key)}, {lit(iv)}, {data_expr(pt, n, k)}, {lit(aad)}, {want_expr(out_)})).toEqual("");')
    # ChaCha20-Poly1305 at the same lengths, and the bare cipher and MAC.
    for j, n in enumerate(lens):
        k += 1
        key = pat(32, 100 + k)
        nonce = pat(12, 200 + k)
        pt = pat(n, k)
        aad = pat(aads[j], 300 + k)
        out_ = ChaCha20Poly1305(key).encrypt(nonce, pt, aad)
        test(f"chacha20-poly1305 pt {n} aad {len(aad)}",
             f'    expect(cc_all(rt {lit(key)}, {lit(nonce)}, {data_expr(pt, n, k)}, {lit(aad)}, {want_expr(out_)})).toEqual("");')
        ctr = (k * 977) % 1000
        test(f"chacha20 xor {n} from block {ctr}",
             f'    expect(xor_all(rt {lit(key)}, {ctr}, {lit(nonce)}, {data_expr(pt, n, k)}, {want_expr(chacha20(key, ctr, nonce, pt))})).toEqual("");')
        test(f"poly1305 {n}",
             f'    expect(poly_all(rt {lit(key)}, {data_expr(pt, n, k)}, {want_expr(Poly1305.generate_tag(key, pt))})).toEqual("");')
    # The block counter wraps modulo 2^32 within one call.
    key = pat(32, 999)
    nonce = pat(12, 998)
    pt = pat(300, 997)
    ks = chacha20(key, 4294967294, nonce, bytes(128)) + chacha20(key, 0, nonce, bytes(172))
    test("chacha20 counter wraps past 2^32 - 1",
         f'    expect(xor_all(rt {lit(key)}, 4294967294, {lit(nonce)}, rt {lit(pt)}, {want_expr(bytes(a ^ b for a, b in zip(pt, ks)))})).toEqual("");')

    text = "\n".join(out)
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            print(f"{OUT} is stale: run tools/gen_aead_ref.py")
            return 1
        print(f"ok: {n_tests} tests current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT} ({n_tests} tests)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
