#!/usr/bin/env python3
"""The verify closure's pins (PLAN-attestation.md §3.2).

The closure is every file of lib/verify/ and every standard-library file
they import, transitively, plus the runtime IR (build/boot/rt.ll and
rt-aarch64.ll). `--write` regenerates compiler/verify_pins.resid with the
SHA-256 of each; `--check` (the default) fails when it differs. Run
`--write` after changing any file in the closure or the runtime, then
rebuild the compiler (and reseed before committing).
"""
import hashlib, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LIB = os.path.join(ROOT, "lib")
OUT = os.path.join(ROOT, "compiler", "verify_pins.resid")
IMP = re.compile(r'^\s*import\s+"([^"]+)"', re.M)

def closure():
    todo = sorted(os.path.join(LIB, "verify", f) for f in os.listdir(os.path.join(LIB, "verify")) if f.endswith(".resid"))
    seen = set()
    while todo:
        p = os.path.normpath(todo.pop())
        if p in seen:
            continue
        seen.add(p)
        for m in IMP.findall(open(p).read()):
            q = os.path.normpath(os.path.join(os.path.dirname(p), m))
            if not os.path.exists(q):
                q = os.path.normpath(os.path.join(LIB, m))
            if not os.path.exists(q):
                sys.exit(f"verify_pins: {p} imports {m}, which is not in the standard library")
            todo.append(q)
    return sorted(os.path.relpath(p, LIB) for p in seen)

def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()

def render():
    ents = [f"{r}={sha(os.path.join(LIB, r))}" for r in closure()]
    for rt in ("rt.ll", "rt-aarch64.ll"):
        ents.append(f"{rt}={sha(os.path.join(ROOT, 'build', 'boot', rt))}")
    body = ",\n        ".join(f'"{e}"' for e in ents)
    return ("// GENERATED by tools/attest/verify_pins.py; do not edit.\n"
            "// verify_pins.resid — the SHA-256 of every file in the verify closure\n"
            "// (lib/verify/ and what it imports) and of the runtime IR this compiler\n"
            "// is released with (PLAN-attestation.md §3.2, compiler/attest.resid).\n\n"
            f"pub List(Str) vp_pins() {{\n    return [\n        {body}\n    ];\n}}\n")

want = render()
if "--write" in sys.argv:
    open(OUT, "w").write(want)
    print(f"verify_pins: wrote {OUT}")
elif not os.path.exists(OUT) or open(OUT).read() != want:
    sys.exit("verify_pins: compiler/verify_pins.resid is stale: run tools/attest/verify_pins.py --write, then rebuild")
else:
    print("verify_pins: ok")
