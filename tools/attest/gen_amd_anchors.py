#!/usr/bin/env python3
"""Generate lib/verify/amd_anchors.resid from the AMD ARK certificates.

Usage: tools/attest/gen_amd_anchors.py ARK_MILAN.der ARK_GENOA.der ARK_TURIN.der
(from https://kdsintf.amd.com/vcek/v1/<product>/cert_chain, the second
certificate). The fingerprint is the SHA-384 of each DER certificate.
"""
import hashlib, sys

RETRIEVED = "2026-10-11"
REVIEWER = "Larry Dewey"
EXPIRES = {"Milan": "2045-10-22", "Genoa": "2047-01-26", "Turin": "2048-05-15"}

def ints(b, per=24):
    xs = [str(x) for x in b]
    rows = [", ".join(xs[i:i + per]) for i in range(0, len(xs), per)]
    return "[\n        " + ",\n        ".join(rows) + "\n    ]"

out = ["// GENERATED by tools/attest/gen_amd_anchors.py from AMD's ARK certificates;",
       "// do not edit. verify/amd_anchors.resid — the AMD SEV-SNP roots",
       "// (PLAN-attestation.md §3.1). Each ARK roots both the VCEK and the VLEK",
       "// chains, so each product has two anchors over one certificate: kind",
       "// AmdVcek (chip-bound) and AmdVlek (fleet-wide). Rebuild-only: a new root",
       "// is a new release.",
       "",
       'import "core.resid";',
       'import "snp.resid";',
       'import "claims.resid";',
       ""]
for prod, path in zip(["Milan", "Genoa", "Turin"], sys.argv[1:4]):
    der = open(path, "rb").read()
    fp = hashlib.sha384(der).hexdigest()
    low = prod.lower()
    src = f"https://kdsintf.amd.com/vcek/v1/{prod}/cert_chain"
    for kind, suffix in (("AmdVcek", ""), ("AmdVlek", "_vlek")):
        out.append(f"/// AMD's {prod} root key (ARK), as the anchor for {'VCEK' if kind == 'AmdVcek' else 'VLEK'}-signed SEV-SNP reports.")
        out.append(f'@anchor(kind = {kind}({prod}), principal = InGuest, formats = [SnpReport], source = "{src}", fingerprint = "sha384:{fp}", retrieved = "{RETRIEVED}", reviewed_by = "{REVIEWER}", algorithms = [RsaPss4096Sha384, EcdsaP384Sha384], expires = "{EXPIRES[prod]}")')
        out.append(f"pub Anchor amd_ark_{low}{suffix}() {{ return anchor_der(amd_ark_{low}_der()); }}")
        out.append("")
    out.append(f"/// The DER bytes of AMD's {prod} ARK certificate.")
    out.append(f"pub List(Int) amd_ark_{low}_der() {{\n    return {ints(der)};\n}}")
    out.append("")
out.append("/// Every AMD SEV-SNP root above, for VCEK- and VLEK-signed reports, as one trust set.")
out.append("@trust(anchors = [" + ", ".join(f"amd_ark_{p.lower()}{s}" for p in ["Milan", "Genoa", "Turin"] for s in ("", "_vlek")) + "])")
out.append("pub Trust amd_roots() { return trust_anchors(); }")
out.append("")
sys.stdout.write("\n".join(out))
