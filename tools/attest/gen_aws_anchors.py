#!/usr/bin/env python3
"""Generate lib/verify/aws_anchors.resid from the AWS Nitro Enclaves root.

Usage: tools/attest/gen_aws_anchors.py ROOT.der
(https://aws-nitro-enclaves.amazonaws.com/AWS_NitroEnclaves_Root-G1.zip;
its SHA-256 is published in the AWS Nitro Enclaves user guide.)
"""
import hashlib, sys

der = open(sys.argv[1], "rb").read()
xs = [str(x) for x in der]
rows = ",\n        ".join(", ".join(xs[i:i + 24]) for i in range(0, len(xs), 24))
fp = hashlib.sha384(der).hexdigest()
sys.stdout.write(f'''// GENERATED by tools/attest/gen_aws_anchors.py from the AWS Nitro
// Enclaves root certificate; do not edit. verify/aws_anchors.resid — the
// root every NSM attestation document's bundle starts at
// (PLAN-attestation.md §3.1). Rebuild-only.

import "core.resid";
import "nsm.resid";
import "claims.resid";

/// The AWS Nitro Enclaves root certificate (G1), as the anchor for NSM attestation documents.
@anchor(kind = Nitro(G1), principal = InGuest, formats = [NsmDocument], source = "https://aws-nitro-enclaves.amazonaws.com/AWS_NitroEnclaves_Root-G1.zip", fingerprint = "sha384:{fp}", retrieved = "2026-10-11", reviewed_by = "Larry Dewey", algorithms = [EcdsaP384Sha384], expires = "2049-10-28")
pub Anchor aws_nitro_root() {{ return anchor_der(aws_nitro_root_der()); }}

/// The DER bytes of the AWS Nitro Enclaves root certificate.
pub List(Int) aws_nitro_root_der() {{
    return [
        {rows}
    ];
}}

/// The AWS Nitro root, for Nitro Enclaves documents, as a trust set.
@trust(anchors = [aws_nitro_root])
pub Trust aws_roots() {{ return trust_anchors(); }}
''')
