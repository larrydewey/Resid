#!/usr/bin/env python3
"""Generate lib/verify/nvidia_anchors.resid from NVIDIA's Device Identity CA.

Usage: tools/attest/gen_nvidia_anchors.py ROOT.der
(verifier_device_root.pem in NVIDIA/nvtrust's local GPU verifier, as DER;
it is also the last certificate of every Hopper GPU's device chain.)
"""
import hashlib, sys

der = open(sys.argv[1], "rb").read()
xs = [str(x) for x in der]
rows = ",\n        ".join(", ".join(xs[i:i + 24]) for i in range(0, len(xs), 24))
fp = hashlib.sha384(der).hexdigest()
sys.stdout.write(f'''// GENERATED by tools/attest/gen_nvidia_anchors.py from NVIDIA's Device Identity
// CA certificate; do not edit. verify/nvidia_anchors.resid — the root
// every NVIDIA GPU's SPDM device certificate chain ends at
// (PLAN-attestation.md §3.1). Rebuild-only.

import "core.resid";
import "spdm.resid";
import "spdm_session.resid";

/// NVIDIA's Device Identity CA, as the anchor for NVIDIA GPU SPDM evidence and sessions.
@anchor(kind = NvidiaDevice(DeviceIdentityCa), principal = AboveKernel, formats = [SpdmEvidence, SpdmSession], source = "https://github.com/NVIDIA/nvtrust (guest_tools/gpu_verifiers/local_gpu_verifier/src/verifier/certs/verifier_device_root.pem)", fingerprint = "sha384:{fp}", retrieved = "2026-10-11", reviewed_by = "Larry Dewey", algorithms = [EcdsaP384Sha384], expires = "9999-12-31")
pub Anchor nvidia_device_root() {{ return anchor_der(nvidia_device_root_der()); }}

/// The DER bytes of NVIDIA's Device Identity CA certificate.
pub List(Int) nvidia_device_root_der() {{
    return [
        {rows}
    ];
}}
''')
