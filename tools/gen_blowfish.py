#!/usr/bin/env python3
"""Writes lib/blowfish_init.resid: Blowfish's initial P-array and S-boxes,
the hexadecimal digits of pi's fractional part (Schneier 1993), computed
here from Machin's formula with integers, not copied from a table.

    python3 tools/gen_blowfish.py
"""
import os
WORDS = 18 + 4 * 256
BITS = WORDS * 32 + 64
def atan_inv(x, one):
    s, t, n, sign = 0, one // x, 1, 1
    while t:
        s += sign * (t // n)
        t //= x * x
        n += 2
        sign = -sign
    return s
one = 1 << BITS
pi = 4 * (4 * atan_inv(5, one) - atan_inv(239, one))
frac = pi - (3 << BITS)
words = [(frac >> (BITS - 32 * (i + 1))) & 0xFFFFFFFF for i in range(WORDS)]
assert words[0] == 0x243F6A88 and words[1] == 0x85A308D3 and words[18] == 0xD1310BA6 and words[-1] == 0x3AC372E6, [hex(w) for w in words[:2] + words[18:19] + words[-1:]]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
lines = ['// GENERATED by tools/gen_blowfish.py: do not edit.',
         '// Blowfish\'s initial state: P[0..17] then S0..S3 (256 words each), the',
         '// hexadecimal digits of pi\'s fractional part.', '',
         'pub List(Int) blowfish_init() {', '    return [']
for i in range(0, WORDS, 8):
    lines.append('        ' + ', '.join(str(w) for w in words[i:i + 8]) + (',' if i + 8 < WORDS else ''))
lines += ['    ];', '}', '']
open(os.path.join(ROOT, 'lib', 'blowfish_init.resid'), 'w').write('\n'.join(lines))
print('wrote lib/blowfish_init.resid')
