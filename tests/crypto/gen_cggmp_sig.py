#!/usr/bin/env python3
"""Generates cggmp_sig_test.resid: the online signing arithmetic of
lib/cggmp_sig.resid. Presignature shares are made in Python the way Taurus's
test does (random additive shares of k and chi = k x); the oracle for the
final signature is OpenSSL's ECDSA verification through the cryptography
package, so (r, s) is checked as a standard ECDSA signature under X.

    python3 tests/crypto/gen_cggmp_sig.py
"""
import hashlib, os, random
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec, utils

HERE = os.path.dirname(os.path.abspath(__file__))
random.seed(2026)
Q = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551
P = 2**256 - 2**224 + 2**192 + 2**96 - 1
A = P - 3
G = (0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296,
     0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5)


def add(p, q):
    if p is None: return q
    if q is None: return p
    if p[0] == q[0]:
        if (p[1] + q[1]) % P == 0: return None
        l = (3 * p[0] * p[0] + A) * pow(2 * p[1], -1, P) % P
    else:
        l = (q[1] - p[1]) * pow(q[0] - p[0], -1, P) % P
    x = (l * l - p[0] - q[0]) % P
    return (x, (l * (p[0] - x) - p[1]) % P)


def mul(k, p):
    r = None
    for b in (bin(k % Q)[2:] if k % Q else ''):
        r = add(r, r)
        if b == '1': r = add(r, p)
    return r


def comp(p): return bytes([2 + (p[1] & 1)]) + p[0].to_bytes(32, 'big')
def n32(v): return v.to_bytes(32, 'big').hex()
def shares(total, n):
    s = [random.randrange(1, Q) for _ in range(n - 1)]
    return s + [(total - sum(s)) % Q]


out = '''// lib/cggmp_sig.resid against Python: presignature shares made as Taurus's
// test does, the final (r, s) checked as a standard ECDSA signature by the
// cryptography package (OpenSSL), and tampered shares located. Generated by
// gen_cggmp_sig.py.

import "../../lib/cggmp_sig.resid";
import "../../lib/cose.resid";
import "../../lib/crypto.resid";

List(UInt(64)) nat(Str hex) { return bn_from_be(cose_hex_decode(rt hex)); }
CvPt cpt(Str hex) { return match cv_dec(cose_hex_decode(hex)) { Some(p) => p, None => cv_inf() }; }
Str hx(List(UInt(64)) x) { return hex_encode(bn_to_be(x, 32)); }

'''
for case, n in enumerate([2, 3, 5]):
    x = random.randrange(1, Q)
    X = mul(x, G)
    k = random.randrange(1, Q)
    kinv = pow(k, -1, Q)
    R = mul(kinv, G)
    chi = x * k % Q
    ks, chis = shares(k, n), shares(chi, n)
    ids = list(range(1, n + 1))
    msg = os.urandom(random.choice([5, 32, 40]))
    digest = hashlib.sha256(msg).digest()
    m = int.from_bytes(digest[:32], 'big') % Q
    r = R[0] % Q
    sig = [(m * ks[i] + r * chis[i]) % Q for i in range(n)]
    s = sum(sig) % Q
    # standard ECDSA verification under X by OpenSSL
    pub = ec.EllipticCurvePublicNumbers(X[0], X[1], ec.SECP256R1()).public_key()
    pub.verify(utils.encode_dss_signature(r, s), digest, ec.ECDSA(utils.Prehashed(hashes.SHA256())))
    rbar = [mul(ks[i] * kinv % Q, G) for i in range(n)]
    ss = [mul(chis[i], R) for i in range(n)]
    pres = (f'CgPresig {{ .id = [], .r = cpt("{comp(R).hex()}"), .ids = {ids}, '
            f'.rbar = [{", ".join(f"cpt({chr(34)}{comp(p).hex()}{chr(34)})" for p in rbar)}], '
            f'.s = [{", ".join(f"cpt({chr(34)}{comp(p).hex()}{chr(34)})" for p in ss)}], '
            f'.kshare = nat("{n32(ks[0])}"), .chi = nat("{n32(chis[0])}") }}')
    dg = '[' + ', '.join(str(b) for b in digest) + ']'
    shares_l = '[' + ', '.join(f'nat("{n32(v)}")' for v in sig) + ']'
    bad = list(sig); bad[n - 1] = (bad[n - 1] + 1) % Q
    bad_l = '[' + ', '.join(f'nat("{n32(v)}")' for v in bad) + ']'
    out += f'''test "signing, {n} signers: shares, assembly, ECDSA verification, tampered share located" {{
    CgPresig pre = {pres};
    List(Int) dg = {dg};
    List(List(UInt(64))) sigs = {shares_l};
    expect(hx(cg_sigma(pre, dg))).toEqual("{n32(sig[0])}");
    expect(hx(cg_s_of(sigs, 0, []))).toEqual("{n32(s)}");
    expect(hex_encode(cg_sig_raw(pre.r, cg_s_of(sigs, 0, [])))).toEqual("{n32(r)}{n32(s)}");
    expect(cg_verify(cpt("{comp(X).hex()}"), dg, pre.r, cg_s_of(sigs, 0, []))).toBeTrue();
    expect(cg_verify(cpt("{comp(mul(2, X)).hex()}"), dg, pre.r, cg_s_of(sigs, 0, []))).toBeFalse();
    expect(cg_verify(cpt("{comp(X).hex()}"), [1, 2, 3], pre.r, cg_s_of(sigs, 0, []))).toBeFalse();
    expect(cg_bad_shares(pre, {ids}, sigs, dg).len()).toEqual(0);
    List(Int) culprits = cg_bad_shares(pre, {ids}, {bad_l}, dg);
    expect(culprits.len()).toEqual(1);
    expect(culprits[0]).toEqual({n});
    expect(cg_presig_ok(pre)).toBeTrue();
}}

'''
open(os.path.join(HERE, 'cggmp_sig_test.resid'), 'w').write(out)
