#!/usr/bin/env python3
"""Generates cggmp_zk_test.resid: proofs made by the Taurus oracle (SHA-256
transcript; build it with cggmp_oracle/setup.sh) checked by the Resid
verifiers in lib/cggmp_zk.resid, with tampered proofs, wrong parameters and a
wrong transcript that must be refused. The other direction (Resid prover, Go
verifier) is cggmp_oracle/interop.py.

    python3 tests/crypto/gen_cggmp_zk.py
"""
import json, os, subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
OR = os.path.join(HERE, 'cggmp_oracle')
GENVEC = os.path.join(OR, '.work', 'genvec')
keys = json.load(open(os.path.join(OR, 'keys.json')))


def run(*a, inp=None):
    return subprocess.run(list(a), input=inp, capture_output=True, text=True, check=True).stdout


def lst(xs): return '[' + ', '.join(f'nat("{x}")' for x in xs) + ']'


out = '''// lib/cggmp_zk.resid verifiers against proofs made by the Taurus
// multi-party-sig oracle (SHA-256 transcript patch). Generated by
// gen_cggmp_zk.py; do not edit by hand. The proofs are inputs to `rt` so
// that they are checked by the compiled verifier.

import "../../lib/cggmp_zk.resid";
import "../../lib/cose.resid";
import "../../lib/crypto.resid";

List(UInt(64)) nat(Str hex) { return bn_from_be(cose_hex_decode(rt hex)); }

Pedersen ped(Str n, Str s, Str t) { return Pedersen {.n = nat(n), .s = nat(s), .t = nat(t)}; }

PrmProof prm(List(List(UInt(64))) as, List(List(UInt(64))) zs) { return PrmProof {.as = as, .zs = zs}; }

ModResponse resp(Bool a, Bool b, Str x, Str z) { return ModResponse {.a = a, .b = b, .x = nat(x), .z = nat(z)}; }

'''
for i, k in enumerate(keys):
    kj = json.dumps(k)
    prm = json.loads(run(GENVEC, 'prm', inp=kj))
    mod = json.loads(run(GENVEC, 'mod', inp=kj))
    assert run(GENVEC, 'verify-prm', inp=json.dumps(prm)).strip() == 'true'
    assert run(GENVEC, 'verify-mod', inp=json.dumps(mod)).strip() == 'true'
    pe = f'ped("{prm["N"]}", "{prm["S"]}", "{prm["T"]}")'
    pf = f'prm({lst(prm["As"])}, {lst(prm["Zs"])})'

    def bump(h):
        v = format(int(h, 16) + 1, 'x')
        return v if len(v) % 2 == 0 else '0' + v

    bad_zs = list(prm['Zs']); bad_zs[17] = bump(bad_zs[17])
    bad_as = list(prm['As']); bad_as[40] = bump(bad_as[40])
    out += f'''test "prm, key {i}: a proof made by Go verifies" {{
    expect(prm_verify({pe}, {pf}, tr_new())).toBeTrue();
}}

test "prm, key {i}: a changed z, a changed A, another transcript, another parameter all fail" {{
    expect(prm_verify({pe}, prm({lst(prm["As"])}, {lst(bad_zs)}), tr_new())).toBeFalse();
    expect(prm_verify({pe}, prm({lst(bad_as)}, {lst(prm["Zs"])}), tr_new())).toBeFalse();
    expect(prm_verify({pe}, {pf}, tr_bytes(tr_new(), [1]))).toBeFalse();
    expect(prm_verify(ped("{prm["N"]}", "{prm["S"]}", "{prm["S"]}"), {pf}, tr_new())).toBeFalse();
    expect(prm_verify(ped("{prm["N"]}", "{prm["T"]}", "{prm["S"]}"), {pf}, tr_new())).toBeFalse();
}}

'''
    resps = ',\n        '.join(f'resp({str(r["A"]).lower()}, {str(r["B"]).lower()}, "{r["X"]}", "{r["Z"]}")' for r in mod['Responses'])
    bad = json.loads(json.dumps(mod)); bad['Responses'][23]['Z'] = bump(bad['Responses'][23]['Z'])
    bad_resps = ',\n        '.join(f'resp({str(r["A"]).lower()}, {str(r["B"]).lower()}, "{r["X"]}", "{r["Z"]}")' for r in bad['Responses'])
    flip = json.loads(json.dumps(mod)); flip['Responses'][5]['A'] = not flip['Responses'][5]['A']
    flip_resps = ',\n        '.join(f'resp({str(r["A"]).lower()}, {str(r["B"]).lower()}, "{r["X"]}", "{r["Z"]}")' for r in flip['Responses'])
    out += f'''test "mod, key {i}: a proof made by Go verifies" {{
    ModProof pf = ModProof {{ .w = nat("{mod["W"]}"), .responses = [
        {resps}] }};
    expect(mod_verify(nat("{mod["N"]}"), pf, tr_new())).toBeTrue();
}}

test "mod, key {i}: a changed z, a flipped sign bit, another transcript, a prime modulus all fail" {{
    ModProof bad = ModProof {{ .w = nat("{mod["W"]}"), .responses = [
        {bad_resps}] }};
    ModProof flip = ModProof {{ .w = nat("{mod["W"]}"), .responses = [
        {flip_resps}] }};
    ModProof pf = ModProof {{ .w = nat("{mod["W"]}"), .responses = [
        {resps}] }};
    expect(mod_verify(nat("{mod["N"]}"), bad, tr_new())).toBeFalse();
    expect(mod_verify(nat("{mod["N"]}"), flip, tr_new())).toBeFalse();
    expect(mod_verify(nat("{mod["N"]}"), pf, tr_bytes(tr_new(), [1]))).toBeFalse();
    expect(mod_verify(nat("{mod["P"]}"), pf, tr_new())).toBeFalse();
}}

'''

# ---- fac and enc: proofs between a prover key and a verifier's Pedersen parameters
out += '''
BnInt zi(Str s) { return zi_from_be(s == "" ? false : false, cose_hex_decode(rt s)); }

'''.replace('s == "" ? false : false', 'false')
out = out.replace('import "../../lib/cggmp_zk.resid";', 'import "../../lib/cggmp_proofs.resid";')
out += '''
BnInt sz(Str s) {
    return if (str_starts_with(s, "-")) { zi_from_be(true, cose_hex_decode(rt str_slice(s, 1, str_len(s)))) } else { zi_from_be(false, cose_hex_decode(rt s)) };
}

'''


def sg(h): return f'sz("{h}")'


def bump_signed(h):
    neg = h.startswith('-')
    v = format(int(h.lstrip('-') or '0', 16) + 1, 'x')
    v = ('0' + v) if len(v) % 2 else v
    return ('-' if neg else '') + v


for i, prover in enumerate(keys):
    ver = keys[(i + 1) % len(keys)]
    two = json.dumps({'Prover': prover, 'Verifier': ver})
    fac = json.loads(run(GENVEC, 'fac', inp=two))
    assert run(GENVEC, 'verify-fac', inp=json.dumps(fac)).strip() == 'true'
    aux = f'ped("{fac["Nhat"]}", "{fac["S"]}", "{fac["T"]}")'
    def facproof(f):
        return (f'FacProof {{ .p = nat("{f["P"]}"), .q = nat("{f["Q"]}"), .a = nat("{f["A"]}"), .b = nat("{f["B"]}"), .t = nat("{f["Tc"]}"), '
                f'.sigma = {sg(f["Sigma"])}, .z1 = {sg(f["Z1"])}, .z2 = {sg(f["Z2"])}, .w1 = {sg(f["W1"])}, .w2 = {sg(f["W2"])}, .v = {sg(f["V"])} }}')
    badf = dict(fac); badf['Z1'] = bump_signed(badf['Z1'])
    badv = dict(fac); badv['V'] = bump_signed(badv['V'])
    out += f'''test "fac, key {i}: a proof made by Go verifies; changes to z1, v, the transcript, N all fail" {{
    expect(fac_verify(nat("{fac["N"]}"), {aux}, {facproof(fac)}, tr_new())).toBeTrue();
    expect(fac_verify(nat("{fac["N"]}"), {aux}, {facproof(badf)}, tr_new())).toBeFalse();
    expect(fac_verify(nat("{fac["N"]}"), {aux}, {facproof(badv)}, tr_new())).toBeFalse();
    expect(fac_verify(nat("{fac["N"]}"), {aux}, {facproof(fac)}, tr_bytes(tr_new(), [1]))).toBeFalse();
    expect(fac_verify(nat("{fac["Nhat"]}"), {aux}, {facproof(fac)}, tr_new())).toBeFalse();
}}

'''
    enc = json.loads(run(GENVEC, 'enc', inp=two))
    assert run(GENVEC, 'verify-enc', inp=json.dumps(enc)).strip() == 'true'
    aux = f'ped("{enc["Nhat"]}", "{enc["S"]}", "{enc["T"]}")'
    def encproof(e):
        return (f'EncProof {{ .s = nat("{e["CS"]}"), .a = nat("{e["CA"]}"), .c = nat("{e["CC"]}"), '
                f'.z1 = {sg(e["Z1"])}, .z2 = nat("{e["Z2"]}"), .z3 = {sg(e["Z3"])} }}')
    bad1 = dict(enc); bad1['Z1'] = bump_signed(bad1['Z1'])
    bad3 = dict(enc); bad3['Z3'] = bump_signed(bad3['Z3'])
    pk = f'paillier_pub(nat("{enc["N"]}"))'
    out += f'''test "enc, key {i}: a proof made by Go verifies; changes to z1, z3, K, the transcript fail" {{
    PaillierPub pk = {pk};
    expect(enc_verify({aux}, pk, nat("{enc["K"]}"), {encproof(enc)}, tr_new())).toBeTrue();
    expect(enc_verify({aux}, pk, nat("{enc["K"]}"), {encproof(bad1)}, tr_new())).toBeFalse();
    expect(enc_verify({aux}, pk, nat("{enc["K"]}"), {encproof(bad3)}, tr_new())).toBeFalse();
    expect(enc_verify({aux}, pk, nat("{enc["CA"]}"), {encproof(enc)}, tr_new())).toBeFalse();
    expect(enc_verify({aux}, pk, nat("{enc["K"]}"), {encproof(enc)}, tr_bytes(tr_new(), [1]))).toBeFalse();
}}

'''

# ---- the remaining proofs: aff-g, aff-p, log*, enc-elg, elog, log, sch
out = out.replace('import "../../lib/cggmp_proofs.resid";', 'import "../../lib/cggmp_proofs.resid";\nimport "../../lib/cggmp_curve.resid";')
out += '''
CvPt cpt(Str hex) { return match cv_dec(cose_hex_decode(rt hex)) { Some(p) => p, None => cv_inf() }; }

'''


def cp(h): return f'cpt("{h}")'
def nt(h): return f'nat("{h}")'


def tamper_hex(h):
    return h[:-1] + ('1' if h[-1] != '1' else '2')


def jgen(kind, two=True):
    inp = json.dumps({'Prover': keys[0], 'Verifier': keys[1]}) if two else ''
    o = run(GENVEC, kind, inp=inp)
    assert run(GENVEC, 'verify-' + kind, inp=o).strip() == 'true'
    return json.loads(o)


def test(name, pos, negs):
    global out
    body = f'    expect({pos}).toBeTrue();\n' + ''.join(f'    expect({n}).toBeFalse();\n' for n in negs)
    out += f'test "{name}" {{\n{body}}}\n\n'


# aff-g
for i in range(2):
    a = jgen('affg')
    pk = lambda n: f'paillier_pub({nt(n)})'
    def pub(a, kv=None):
        return (f'AffgPublic {{ .kv = {nt(kv or a["Kv"])}, .dv = {nt(a["Dv"])}, .fp = {nt(a["Fp"])}, .xp = {cp(a["Xp"])}, '
                f'.prover = {pk(a["NP"])}, .verifier = {pk(a["NV"])}, .aux = ped("{a["Nhat"]}", "{a["S"]}", "{a["T"]}") }}')
    def prf(a):
        return (f'AffgProof {{ .a = {nt(a["A"])}, .bx = {cp(a["Bx"])}, .by = {nt(a["By"])}, .e = {nt(a["E"])}, .s = {nt(a["SS"])}, .f = {nt(a["F"])}, .t = {nt(a["TT"])}, '
                f'.z1 = {sg(a["Z1"])}, .z2 = {sg(a["Z2"])}, .z3 = {sg(a["Z3"])}, .z4 = {sg(a["Z4"])}, .w = {nt(a["W"])}, .wy = {nt(a["Wy"])} }}')
    bad1 = dict(a); bad1['Z1'] = bump_signed(a['Z1'])
    bad2 = dict(a); bad2['Z2'] = bump_signed(a['Z2'])
    bad3 = dict(a); bad3['Z4'] = bump_signed(a['Z4'])
    bad4 = dict(a); bad4['Wy'] = tamper_hex(a['Wy'])
    test(f'aff-g {i}: a proof made by Go verifies; changed z1, z2, z4, wy, Xp, Kv, transcript fail',
         f'affg_verify({pub(a)}, {prf(a)}, tr_new())',
         [f'affg_verify({pub(a)}, {prf(b)}, tr_new())' for b in (bad1, bad2, bad3, bad4)]
         + [f'affg_verify({pub(a)}, {prf(a)}, tr_bytes(tr_new(), [1]))',
            f'affg_verify({pub(a, kv=a["Dv"])}, {prf(a)}, tr_new())'])

# aff-p
for i in range(2):
    a = jgen('affp')
    pk = lambda n: f'paillier_pub({nt(n)})'
    def pub(a):
        return (f'AffpPublic {{ .kv = {nt(a["Kv"])}, .dv = {nt(a["Dv"])}, .fp = {nt(a["Fp"])}, .xp = {nt(a["Xp"])}, '
                f'.prover = {pk(a["NP"])}, .verifier = {pk(a["NV"])}, .aux = ped("{a["Nhat"]}", "{a["S"]}", "{a["T"]}") }}')
    def prf(a):
        return (f'AffpProof {{ .a = {nt(a["A"])}, .bx = {nt(a["Bx"])}, .by = {nt(a["By"])}, .e = {nt(a["E"])}, .s = {nt(a["SS"])}, .f = {nt(a["F"])}, .t = {nt(a["TT"])}, '
                f'.z1 = {sg(a["Z1"])}, .z2 = {sg(a["Z2"])}, .z3 = {sg(a["Z3"])}, .z4 = {sg(a["Z4"])}, .w = {nt(a["W"])}, .wx = {nt(a["Wx"])}, .wy = {nt(a["Wy"])} }}')
    bads = []
    for fld in ('Z1', 'Z2', 'Z3', 'Z4'):
        b = dict(a); b[fld] = bump_signed(a[fld]); bads.append(b)
    for fld in ('Wx', 'Wy'):
        b = dict(a); b[fld] = tamper_hex(a[fld]); bads.append(b)
    test(f'aff-p {i}: a proof made by Go verifies; changes to z1 to z4, wx, wy, transcript fail',
         f'affp_verify({pub(a)}, {prf(a)}, tr_new())',
         [f'affp_verify({pub(a)}, {prf(b)}, tr_new())' for b in bads] + [f'affp_verify({pub(a)}, {prf(a)}, tr_bytes(tr_new(), [1]))'])

# log*
for i in range(2):
    a = jgen('logstar')
    pub = (f'LogstarPublic {{ .c = {nt(a["C"])}, .x = {cp(a["X"])}, .g = {cp(a["G"])}, .prover = paillier_pub({nt(a["N"])}), '
           f'.aux = ped("{a["Nhat"]}", "{a["S"]}", "{a["T"]}") }}')
    def prf(a):
        return (f'LogstarProof {{ .s = {nt(a["CS"])}, .a = {nt(a["A"])}, .y = {cp(a["Y"])}, .d = {nt(a["D"])}, '
                f'.z1 = {sg(a["Z1"])}, .z2 = {nt(a["Z2"])}, .z3 = {sg(a["Z3"])} }}')
    b1 = dict(a); b1['Z1'] = bump_signed(a['Z1'])
    b2 = dict(a); b2['Z2'] = tamper_hex(a['Z2'])
    b3 = dict(a); b3['Z3'] = bump_signed(a['Z3'])
    pub_other = pub.replace(f'.g = {cp(a["G"])}', f'.g = {cp(a["X"])}')
    test(f'log* {i}: a proof made by Go verifies; changes to z1, z2, z3, the base, transcript fail',
         f'logstar_verify({pub}, {prf(a)}, tr_new())',
         [f'logstar_verify({pub}, {prf(b)}, tr_new())' for b in (b1, b2, b3)]
         + [f'logstar_verify({pub_other}, {prf(a)}, tr_new())', f'logstar_verify({pub}, {prf(a)}, tr_bytes(tr_new(), [1]))'])

# enc-elg
for i in range(2):
    a = jgen('encelg')
    pub = (f'EncelgPublic {{ .c = {nt(a["C"])}, .a = {cp(a["A"])}, .b = {cp(a["B"])}, .x = {cp(a["X"])}, .prover = paillier_pub({nt(a["N"])}), '
           f'.aux = ped("{a["Nhat"]}", "{a["S"]}", "{a["T"]}") }}')
    def prf(a):
        return (f'EncelgProof {{ .s = {nt(a["CS"])}, .d = {nt(a["D"])}, .y = {cp(a["Y"])}, .z = {cp(a["Z"])}, .t = {nt(a["TT"])}, '
                f'.z1 = {sg(a["Z1"])}, .w = {nt(a["W"])}, .z2 = {nt(a["Z2"])}, .z3 = {sg(a["Z3"])} }}')
    b1 = dict(a); b1['Z1'] = bump_signed(a['Z1'])
    b2 = dict(a); b2['W'] = tamper_hex(a['W'])
    b3 = dict(a); b3['Z3'] = bump_signed(a['Z3'])
    test(f'enc-elg {i}: a proof made by Go verifies; changes to z1, w, z3, transcript fail',
         f'encelg_verify({pub}, {prf(a)}, tr_new())',
         [f'encelg_verify({pub}, {prf(b)}, tr_new())' for b in (b1, b2, b3)] + [f'encelg_verify({pub}, {prf(a)}, tr_bytes(tr_new(), [1]))'])

# elog, log, sch
for i in range(2):
    a = jgen('elog', False)
    pub = f'ElogPublic {{ .el = {cp(a["EL"])}, .em = {cp(a["EM"])}, .x = {cp(a["X"])}, .base = {cp(a["Base"])}, .y = {cp(a["Y"])} }}'
    prf = lambda a: f'ElogProof {{ .a = {cp(a["A"])}, .n = {cp(a["N"])}, .b = {cp(a["B"])}, .z = {nt(a["Z"])}, .u = {nt(a["U"])} }}'
    b1 = dict(a); b1['Z'] = tamper_hex(a['Z'])
    b2 = dict(a); b2['U'] = tamper_hex(a['U'])
    test(f'elog {i}: a proof made by Go verifies; changes to z, u, transcript fail', f'elog_verify({pub}, {prf(a)}, tr_new())',
         [f'elog_verify({pub}, {prf(b1)}, tr_new())', f'elog_verify({pub}, {prf(b2)}, tr_new())', f'elog_verify({pub}, {prf(a)}, tr_bytes(tr_new(), [1]))'])

    a = jgen('log', False)
    pub = f'LogPublic {{ .h = {cp(a["H"])}, .x = {cp(a["X"])}, .y = {cp(a["Y"])} }}'
    prf = lambda a: f'LogProof {{ .a = {cp(a["A"])}, .b = {cp(a["B"])}, .c = {cp(a["C"])}, .z1 = {nt(a["Z1"])}, .z2 = {nt(a["Z2"])} }}'
    b1 = dict(a); b1['Z1'] = tamper_hex(a['Z1'])
    b2 = dict(a); b2['Z2'] = tamper_hex(a['Z2'])
    test(f'log {i}: a proof made by Go verifies; changes to z1, z2, transcript fail', f'log_verify({pub}, {prf(a)}, tr_new())',
         [f'log_verify({pub}, {prf(b1)}, tr_new())', f'log_verify({pub}, {prf(b2)}, tr_new())', f'log_verify({pub}, {prf(a)}, tr_bytes(tr_new(), [1]))'])

    a = jgen('sch', False)
    prf = lambda a: f'SchProof {{ .c = {cp(a["C"])}, .z = {nt(a["Z"])} }}'
    b1 = dict(a); b1['Z'] = tamper_hex(a['Z'])
    test(f'sch {i}: a proof made by Go verifies; changes to z, the base, transcript fail',
         f'sch_verify({cp(a["X"])}, {cp(a["G"])}, {prf(a)}, tr_new())',
         [f'sch_verify({cp(a["X"])}, {cp(a["G"])}, {prf(b1)}, tr_new())', f'sch_verify({cp(a["X"])}, {cp(a["X"])}, {prf(a)}, tr_new())',
          f'sch_verify({cp(a["X"])}, {cp(a["G"])}, {prf(a)}, tr_bytes(tr_new(), [1]))'])


# nth, with the plaintext and hidden nonce a decryption recovers (abort openings)
out = out.replace('import "../../lib/cggmp_proofs.resid";', 'import "../../lib/cggmp.resid";', 1)
for i in range(2):
    o = run(GENVEC, 'nth', inp=json.dumps(keys[i]))
    assert run(GENVEC, 'verify-nth', inp=o).strip() == 'true'
    a = json.loads(o)
    def opn(a, hidden=None):
        return (f'CgOpen {{ .plain = {sg(a["M"])}, .hidden = {nt(hidden or a["R"])}, .proof = NthProof {{ .a = {nt(a["A"])}, .z = {nt(a["Z"])} }} }}')
    b1 = dict(a); b1['Z'] = bump_signed(a["Z"])
    b2 = dict(a); b2['M'] = bump_signed(a['M'])
    pk = f'paillier_pub({nt(a["N"])})'
    test(f'nth {i}: an opening made by Go verifies; changes to z, the plaintext, the ciphertext, transcript fail',
         f'cg_open_ok({pk}, {nt(a["C"])}, {opn(a)}, tr_new())',
         [f'cg_open_ok({pk}, {nt(a["C"])}, {opn(b1)}, tr_new())', f'cg_open_ok({pk}, {nt(a["C"])}, {opn(b2)}, tr_new())',
          f'cg_open_ok({pk}, {nt(a["R"])}, {opn(a)}, tr_new())', f'cg_open_ok({pk}, {nt(a["C"])}, {opn(a)}, tr_bytes(tr_new(), [1]))'])

open(os.path.join(HERE, 'cggmp_zk_test.resid'), 'w').write(out)
