#!/usr/bin/env python3
"""Generates paillier_test.resid: lib/paillier.resid against an independent
Python implementation of Paillier (Python ints; primes from the
cryptography package's RSA key generation).

    python3 tests/crypto/gen_paillier.py
"""
import math, os, random
from cryptography.hazmat.primitives.asymmetric import rsa

HERE = os.path.dirname(os.path.abspath(__file__))
random.seed(7)


def hx(n):
    s = format(n, 'x')
    return '' if n == 0 else (s if len(s) % 2 == 0 else '0' + s)

def N(n): return f'bn_from_be(cose_hex_decode("{hx(n)}"))'

# Python Paillier, written for this oracle only.
def keygen(bits):
    k = rsa.generate_private_key(public_exponent=65537, key_size=bits)
    nums = k.private_numbers()
    p, q = nums.p, nums.q
    return p, q

def enc(n, m, rho):
    n2 = n * n
    return (pow(1 + n, m, n2) * pow(rho, n, n2)) % n2   # g = 1 + N, computed as a power (not 1 + mN)

def dec(p, q, c):
    n = p * q
    lam = math.lcm(p - 1, q - 1)       # lambda, not phi: a different route to the same plaintext
    mu = pow(lam, -1, n)
    return (((pow(c, lam, n * n) - 1) // n) * mu) % n

out = '''// lib/paillier.resid against a separate Python implementation of Paillier
// (g = 1 + N by modular power, decryption with lambda = lcm(p-1, q-1)). Keys
// are 1024-bit and 2048-bit moduli. Generated by gen_paillier.py.

import "../../lib/paillier.resid";
import "../../lib/bignum.resid";
import "../../lib/cose.resid";
import "../../lib/crypto.resid";

Str hx(List(UInt(64)) x) { return hex_encode(bn_to_be(x, 0)); }

'''
for ki, bits in enumerate([1024, 1024, 2048]):
    p, q = keygen(bits)
    n = p * q
    b = f'    PaillierPub k = paillier_pub({N(n)});\n'
    b += f'    Option(PaillierSec) so = paillier_sec({N(p)}, {N(q)});\n'
    b += '    PaillierSec s = so else { PaillierSec {.p = [], .q = [], .phi = [], .phi_inv = []} };\n'
    for j in range(4):
        m = random.choice([0, 1, n - 1, random.randrange(n), random.randrange(n)])
        rho = random.randrange(2, n)
        while math.gcd(rho, n) != 1: rho = random.randrange(2, n)
        c = enc(n, m, rho)
        assert dec(p, q, c) == m
        m2 = random.randrange(n); rho2 = random.randrange(2, n)
        c2 = enc(n, m2, rho2)
        kk = random.randrange(n)
        on = j % 2
        r = 'rt ' if on else ''
        b += f'    // case {j}\n'
        b += f'    List(UInt(64)) c{j} = paillier_enc(k, bn_from_be(cose_hex_decode({r}"{hx(m)}")), {N(rho)});\n'
        b += f'    expect(hx(c{j})).toEqual("{hx(c)}");\n'
        b += f'    expect(hx(paillier_dec(s, k, {N(c)}))).toEqual("{hx(m)}");\n'
        b += f'    expect(hx(paillier_add(k, {N(c)}, {N(c2)}))).toEqual("{hx(c * c2 % (n * n))}");\n'
        b += f'    expect(hx(paillier_dec(s, k, paillier_add(k, {N(c)}, {N(c2)})))).toEqual("{hx((m + m2) % n)}");\n'
        b += f'    expect(hx(paillier_mul(k, {N(c)}, {N(kk)}))).toEqual("{hx(pow(c, kk, n * n))}");\n'
        b += f'    expect(hx(paillier_dec(s, k, paillier_mul(k, {N(c)}, {N(kk)})))).toEqual("{hx(kk * m % n)}");\n'
    out += f'test "paillier, {bits}-bit modulus, key {ki}" {{\n{b}}}\n\n'
open(os.path.join(HERE, 'paillier_test.resid'), 'w').write(out)
