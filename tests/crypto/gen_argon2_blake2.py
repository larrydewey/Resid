#!/usr/bin/env python3
"""Generates argon2id_test.resid, blake2b_test.resid and sha1_test.resid.

Every expected value comes from an independent implementation, never from
lib/ itself: OpenSSL's Argon2id (`openssl kdf ARGON2ID`, which reproduces the
RFC 9106 vector), Python's hashlib.blake2b and hashlib.sha1, and hmac.
Half of each file's cases pass their inputs through `rt`, so they run in the
compiled program instead of being folded by the compiler.

    python3 tests/crypto/gen_argon2_blake2.py
"""
import hashlib, hmac, os, random, subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
random.seed(20261014)
rb = lambda n: bytes(random.randrange(256) for _ in range(n))


OPENED = '''
Str hx(List(Int) b) { return hex_encode(b); }

List(Int) widen_u8(List(UInt(8)) b, Int i, ListBuf(Int) acc) {
    if (i >= b.len()) { return acc.finish(); }
    return widen_u8(b, i + 1, acc.push((Int) b[i]));
}

@requires(declassify)
List(Int) opened(List(Secret(UInt(8))) b) {
    return widen_u8(declassify(secret_join(b), "test compares to the reference digest"), 0, ListBuf());
}

'''


def kdf(pw, salt, sec, ad, lanes, mem, it, tl):
    cmd = ['openssl', 'kdf', '-keylen', str(tl), '-binary', '-kdfopt', 'hexpass:' + pw.hex(),
           '-kdfopt', 'hexsalt:' + salt.hex(), '-kdfopt', f'iter:{it}', '-kdfopt', f'memcost:{mem}',
           '-kdfopt', f'lanes:{lanes}', '-kdfopt', 'threads:1']
    if sec: cmd += ['-kdfopt', 'hexsecret:' + sec.hex()]
    if ad: cmd += ['-kdfopt', 'hexad:' + ad.hex()]
    cmd.append('ARGON2ID')
    return subprocess.run(cmd, check=True, capture_output=True).stdout


def rt(xs, on):
    # A list of byte values, wrapped so the compiler cannot fold it.
    return f'rt {list(xs)}' if on else f'{list(xs)}'


def argon2():
    out = '''// Argon2id (lib/argon2g.resid) against OpenSSL's Argon2id. Case 0 is the RFC
// 9106 vector. The cases vary lanes, memory, passes, tag length (above 64
// this exercises H'), and the lengths of password, salt, secret key and
// associated data. Odd cases run on `rt` inputs (compiled, not folded).
// Generated by gen_argon2_blake2.py; do not edit by hand.

import "../../lib/argon2g.resid";
import "../../lib/word.resid";
import "../../lib/crypto.resid";
''' + OPENED + '''
'''
    cases = [(b'\x01' * 32, b'\x02' * 16, b'\x03' * 8, b'\x04' * 12, 4, 32, 3, 32)]
    for _ in range(40):
        lanes = random.randint(1, 4)
        cases.append((rb(random.choice([0, 1, 5, 32, 80])), rb(random.randint(8, 32)),
                      rb(random.choice([0, 0, 8, 20])), rb(random.choice([0, 0, 12, 30])),
                      lanes, random.randint(8 * lanes, 90), random.randint(1, 4),
                      random.choice([4, 16, 32, 64, 65, 96, 100, 200])))
    for i, (pw, salt, sec, ad, lanes, mem, it, tl) in enumerate(cases):
        on = i % 2 == 1
        exp = list(kdf(pw, salt, sec, ad, lanes, mem, it, tl))
        m = f'rt {mem}' if on else f'{mem}'
        out += f'''test "argon2id case {i}: p={lanes} m={mem} t={it} T={tl}" {{
    List(Int) tag = argon2id({rt(pw, on)}, {list(salt)}, {rt(sec, on)}, {list(ad)}, {lanes}, {m}, {it}, {tl});
    expect(hx(tag)).toEqual("{bytes(exp).hex()}");
}}

'''
        if i % 4 == 0:
            out += f'''@requires(declassify)
test "argon2id secret copy, case {i}" {{
    List(Secret(UInt(8))) tag = argon2id(secret_bytes({rt(pw, True)}), {list(salt)}, secret_bytes({rt(sec, True)}), {list(ad)}, {lanes}, rt {mem}, {it}, {tl});
    expect(hx(opened(tag))).toEqual("{bytes(exp).hex()}");
}}

'''
    open(os.path.join(HERE, 'argon2id_test.resid'), 'w').write(out)


def blake2b():
    out = '''// BLAKE2b (lib/blake2bg.resid) against Python's hashlib.blake2b, unkeyed, over
// message lengths around the 128-byte block boundaries and digest lengths
// 1 to 64. Odd cases run on `rt` input. Generated by gen_argon2_blake2.py.

import "../../lib/blake2bg.resid";
import "../../lib/word.resid";
import "../../lib/crypto.resid";
''' + OPENED + '''
'''
    lens = [0, 1, 3, 63, 64, 127, 128, 129, 255, 256, 257, 300, 1000]
    i = 0
    for n in lens:
        for o in (1, 32, 64, random.randint(2, 63)):
            m = rb(n)
            exp = list(hashlib.blake2b(m, digest_size=o).digest())
            on = i % 2 == 1
            out += f'''test "blake2b case {i}: len={n} out={o}" {{
    List(Int) m = {rt(m, on)};
    expect(hx(blake2bg(m, {o}))).toEqual("{bytes(exp).hex()}");
}}

'''
            if i % 4 == 0:
                out += f'''@requires(declassify)
test "blake2b secret copy, case {i}" {{
    List(Secret(UInt(8))) d = blake2bg(secret_bytes({rt(m, True)}), {o});
    expect(hx(opened(d))).toEqual("{bytes(exp).hex()}");
}}

'''
            i += 1
    open(os.path.join(HERE, 'blake2b_test.resid'), 'w').write(out)


def sha1():
    out = '''// SHA-1 and HMAC-SHA-1 (lib/sha1g.resid) against Python's hashlib.sha1 and
// hmac. Message lengths straddle the 55/56/64-byte padding boundaries; HMAC
// keys are shorter than, equal to and longer than the 64-byte block. Odd
// cases run on `rt` input. Generated by gen_argon2_blake2.py.

import "../../lib/sha1g.resid";
import "../../lib/word.resid";
import "../../lib/crypto.resid";
''' + OPENED + '''
'''
    i = 0
    for n in [0, 1, 3, 55, 56, 57, 63, 64, 65, 119, 120, 128, 200, 1000]:
        m = rb(n)
        on = i % 2 == 1
        out += f'''test "sha1 case {i}: len={n}" {{
    List(Int) m = {rt(m, on)};
    expect(hx(sha1g(m))).toEqual("{hashlib.sha1(m).hexdigest()}");
}}

'''
        if i % 3 == 0:
            out += f'''@requires(declassify)
test "sha1 secret copy, case {i}" {{
    List(Secret(UInt(8))) d = sha1g(secret_bytes({rt(m, True)}));
    expect(hx(opened(d))).toEqual("{hashlib.sha1(m).hexdigest()}");
}}

'''
        i += 1
    for kn in [0, 1, 20, 63, 64, 65, 100]:
        for mn in [0, 8, 64, 100]:
            k, m = rb(kn), rb(mn)
            on = i % 2 == 1
            out += f'''test "hmac-sha1 case {i}: key={kn} msg={mn}" {{
    List(Int) k = {rt(k, on)};
    List(Int) m = {rt(m, on)};
    expect(hx(hmac1g(k, m))).toEqual("{hmac.new(k, m, hashlib.sha1).hexdigest()}");
}}

'''
            if i % 3 == 0:
                out += f'''@requires(declassify)
test "hmac-sha1 secret copy, case {i}" {{
    List(Secret(UInt(8))) d = hmac1g(secret_bytes({rt(k, True)}), secret_bytes({rt(m, True)}));
    expect(hx(opened(d))).toEqual("{hmac.new(k, m, hashlib.sha1).hexdigest()}");
}}

'''
            i += 1
    open(os.path.join(HERE, 'sha1_test.resid'), 'w').write(out)


def utf8():
    out = '''// bytes_of, cbe_text and sha256(Str) are UTF-8 (RFC 3629): one to four bytes
// per code point, not one byte per code point. Expected values come from
// Python's str.encode, hashlib and a separate CBOR head encoder. Generated by
// gen_argon2_blake2.py.

import "../../lib/crypto.resid";
import "../../lib/cose.resid";

Str hx(List(Int) b) { return hex_encode(b); }

'''
    texts = ['', 'abc', 'p\u00e4ssw\u00f6rd', '\u20ac', '\U0001F600', 'a\u00e9\u20ac\U0001F600z',
             '\u0000'[:0] + 'caf\u00e9', '\u07ff\u0800\uffff\U00010000\U0010ffff', 'x' * 130 + '\u00e9']
    texts += [''.join(chr(random.choice([0x41, 0xe9, 0x20ac, 0x1F600, 0x7ff, 0x800])) for _ in range(n)) for n in (5, 40, 90)]
    for i, t in enumerate(texts):
        b = t.encode()
        def head3(n):
            return bytes([0x60 | n]) if n < 24 else bytes([0x78, n]) if n < 256 else bytes([0x79]) + n.to_bytes(2, 'big')
        cbor = head3(len(b)) + b
        lit = t.replace('\\', '\\\\').replace('"', '\\"')
        out += f'''test "utf8 case {i}: {len(t)} code points, {len(b)} bytes" {{
    expect(hx(bytes_of("{lit}"))).toEqual("{b.hex()}");
    expect(hx(cbe_text("{lit}", []))).toEqual("{cbor.hex()}");
    expect(sha256("{lit}")).toEqual("{hashlib.sha256(b).hexdigest()}");
}}

'''
    open(os.path.join(HERE, 'utf8_test.resid'), 'w').write(out)


argon2(); blake2b(); sha1(); utf8()
