#!/usr/bin/env python3
"""Generates bigint_test.resid: lib/bigint.resid against Python's signed int.

    python3 tests/crypto/gen_bigint.py
"""
import os, random
HERE = os.path.dirname(os.path.abspath(__file__))
random.seed(99)


def hx(n):
    n = abs(n)
    s = format(n, 'x')
    return '' if n == 0 else (s if len(s) % 2 == 0 else '0' + s)


def Z(n, on):
    return f'zi_from_be({"true" if n < 0 else "false"}, cose_hex_decode({"rt " if on else ""}"{hx(n)}"))'


def sg(n): return ('-' if n < 0 else '') + hx(n)


out = '''// lib/bigint.resid against Python's signed int. Generated by gen_bigint.py.

import "../../lib/bigint.resid";
import "../../lib/cose.resid";
import "../../lib/crypto.resid";

Str hz(BnInt a) { return (if (a.neg) { "-" } else { "" }) + hex_encode(bn_to_be(a.mag, 0)); }

'''
vals = [0, 1, -1, 2**64, -(2**64), 2**64 - 1, -(2**128), 2**255, -(2**255)] + [random.randint(-(2**random.choice([8, 64, 100, 300, 800])), 2**random.choice([8, 64, 100, 300, 800])) for _ in range(40)]
b = ''
for i in range(60):
    x, y = random.choice(vals), random.choice(vals)
    on = i % 2 == 1
    b += f'    expect(hz(zi_add({Z(x, on)}, {Z(y, on)}))).toEqual("{sg(x + y)}");\n'
    b += f'    expect(hz(zi_sub({Z(x, on)}, {Z(y, on)}))).toEqual("{sg(x - y)}");\n'
    b += f'    expect(hz(zi_mul({Z(x, on)}, {Z(y, on)}))).toEqual("{sg(x * y)}");\n'
    b += f'    expect(zi_cmp({Z(x, on)}, {Z(y, on)})).toEqual({(x > y) - (x < y)});\n'
    b += f'    expect(hz(zi_neg({Z(x, on)}))).toEqual("{sg(-x)}");\n'
out += f'test "signed add, sub, mul, cmp, neg" {{\n{b}}}\n\n'
b = ''
for i in range(40):
    m = random.getrandbits(random.choice([64, 128, 512, 1024])) | 1 | (1 << 60)
    x = random.choice(vals)
    on = i % 2 == 1
    b += f'    expect(hex_encode(bn_to_be(zi_mod({Z(x, on)}, bn_from_be(cose_hex_decode("{hx(m)}"))), 0))).toEqual("{hx(x % m)}");\n'
out += f'test "signed mod" {{\n{b}}}\n\n'
b = ''
for i in range(30):
    bits = random.choice([128, 512, 1024])
    m = random.getrandbits(bits) | 1 | (1 << (bits - 1))
    base = random.randrange(2, m)
    while __import__('math').gcd(base, m) != 1: base = random.randrange(2, m)
    e = random.randint(-(2**random.choice([8, 64, 300])), 2**random.choice([8, 64, 300]))
    on = i % 2 == 1
    want = pow(base, e, m)
    b += f'    expect(hex_encode(bn_to_be(zi_modexp(bn_from_be(cose_hex_decode("{hx(base)}")), {Z(e, on)}, bn_from_be(cose_hex_decode("{hx(m)}"))), 0))).toEqual("{hx(want)}");\n'
out += f'test "modular exponentiation with signed exponents" {{\n{b}}}\n\n'
open(os.path.join(HERE, 'bigint_test.resid'), 'w').write(out)
