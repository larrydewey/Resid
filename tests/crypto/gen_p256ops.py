#!/usr/bin/env python3
"""Generates p256ops_test.resid and shamir_test.resid.

The oracle is a separate P-256 implementation in Python integers (affine
formulas), itself checked here against the cryptography package (k*G by key
derivation, k*Q by ECDH) before it is trusted. Shamir, Feldman commitments,
Lagrange coefficients and the additive conversion are computed in Python.

    python3 tests/crypto/gen_p256ops.py
"""
import os, random
from cryptography.hazmat.primitives.asymmetric import ec

HERE = os.path.dirname(os.path.abspath(__file__))
random.seed(256)

P = 2**256 - 2**224 + 2**192 + 2**96 - 1
A = P - 3
Q = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551
G = (0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296,
     0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5)


def inv(a, m): return pow(a, -1, m)


def add(p, q):
    if p is None: return q
    if q is None: return p
    if p[0] == q[0]:
        if (p[1] + q[1]) % P == 0: return None
        l = (3 * p[0] * p[0] + A) * inv(2 * p[1], P) % P
    else:
        l = (q[1] - p[1]) * inv(q[0] - p[0], P) % P
    x = (l * l - p[0] - q[0]) % P
    return (x, (l * (p[0] - x) - p[1]) % P)


def mul(k, p):
    r = None
    for b in bin(k % Q)[2:] if k % Q else '':
        r = add(r, r)
        if b == '1': r = add(r, p)
    return r


def neg(p): return None if p is None else (p[0], (-p[1]) % P)


def enc(p): return b'' if p is None else b'\x04' + p[0].to_bytes(32, 'big') + p[1].to_bytes(32, 'big')


# Trust the oracle only after it agrees with cryptography.
for _ in range(20):
    k = random.randrange(1, Q)
    pub = ec.derive_private_key(k, ec.SECP256R1()).public_key().public_numbers()
    assert mul(k, G) == (pub.x, pub.y)
    k2 = random.randrange(1, Q)
    peer = ec.derive_private_key(k2, ec.SECP256R1())
    shared = ec.derive_private_key(k, ec.SECP256R1()).exchange(ec.ECDH(), peer.public_key())
    qpt = mul(k2, G)
    assert mul(k, qpt)[0].to_bytes(32, 'big') == shared


def hx(n):
    s = format(n, 'x')
    return '' if n == 0 else (s if len(s) % 2 == 0 else '0' + s)


def S(n): return f'p256_from_be(cose_hex_decode("{n.to_bytes(32, "big").hex()}"))'
def PT(p): return f'pt_dec(cose_hex_decode("{enc(p).hex()}"))'
def sc_hex(): return 'hex_encode(sc_to_be(x))'


head = '''import "../../lib/p256ops.resid";
import "../../lib/shamir.resid";
import "../../lib/cose.resid";
import "../../lib/crypto.resid";

Str hs(UInt(576) x) { return hex_encode(sc_to_be(x)); }
Str hp(P256Aff p) { return hex_encode(pt_enc(p)); }
UInt(576) sc(Str hex) { return p256_from_be(cose_hex_decode(hex)); }
P256Aff pt(Str hex) { return pt_dec(cose_hex_decode(hex)); }

'''
out = '// lib/p256ops.resid against a Python P-256 (checked against cryptography). Generated by gen_p256ops.py.\n\n' + head


def blk(name, body):
    global out
    out += f'test "{name}" {{\n{body}}}\n\n'


edge = [0, 1, 2, Q - 1, Q - 2, 2**255, 2**128]
b = ''
for i in range(40):
    x = random.choice(edge + [random.randrange(Q) for _ in range(4)])
    y = random.choice(edge + [random.randrange(Q) for _ in range(4)])
    on = 'rt ' if i % 2 else ''
    b += f'    expect(hs(sc_add(sc({on}"{x.to_bytes(32,"big").hex()}"), sc("{y.to_bytes(32,"big").hex()}")))).toEqual("{((x+y)%Q).to_bytes(32,"big").hex()}");\n'
    b += f'    expect(hs(sc_sub(sc("{x.to_bytes(32,"big").hex()}"), sc("{y.to_bytes(32,"big").hex()}")))).toEqual("{((x-y)%Q).to_bytes(32,"big").hex()}");\n'
    b += f'    expect(hs(sc_mul(sc({on}"{x.to_bytes(32,"big").hex()}"), sc("{y.to_bytes(32,"big").hex()}")))).toEqual("{((x*y)%Q).to_bytes(32,"big").hex()}");\n'
    b += f'    expect(hs(sc_neg(sc("{x.to_bytes(32,"big").hex()}")))).toEqual("{((-x)%Q).to_bytes(32,"big").hex()}");\n'
    if x: b += f'    expect(hs(sc_inv(sc({on}"{x.to_bytes(32,"big").hex()}")))).toEqual("{inv(x,Q).to_bytes(32,"big").hex()}");\n'
blk('scalars mod n', b)

b = ''
for ln in [1, 5, 31, 32, 33, 48, 64, 80]:
    for _ in range(3):
        v = random.getrandbits(8 * ln)
        raw = v.to_bytes(ln, 'big')
        b += f'    expect(hs(sc_from_be(cose_hex_decode("{raw.hex()}")))).toEqual("{(v%Q).to_bytes(32,"big").hex()}");\n'
blk('reduction of long integers mod n', b)

b = ''
for i in range(24):
    k = random.choice([1, 2, Q - 1, Q - 2, random.randrange(1, Q), random.randrange(1, Q)])
    b += f'    expect(hp(pt_mul_base({S(k)}))).toEqual("{enc(mul(k, G)).hex()}");\n'
    q = mul(random.randrange(1, Q), G)
    k2 = random.choice([1, Q - 1, random.randrange(1, Q)])
    b += f'    expect(hp(pt_mul({S(k2)}, {PT(q)}))).toEqual("{enc(mul(k2, q)).hex()}");\n'
blk('P-256 scalar multiplication', b)

b = ''
for i in range(20):
    p = mul(random.randrange(1, Q), G); q = mul(random.randrange(1, Q), G)
    b += f'    expect(hp(pt_add({PT(p)}, {PT(q)}))).toEqual("{enc(add(p, q)).hex()}");\n'
    b += f'    expect(hp(pt_add({PT(p)}, {PT(p)}))).toEqual("{enc(add(p, p)).hex()}");\n'
    b += f'    expect(hp(pt_add({PT(p)}, pt_neg({PT(p)})))).toEqual("");\n'
    b += f'    expect(hp(pt_add({PT(p)}, p256_bad()))).toEqual("{enc(p).hex()}");\n'
    b += f'    expect(hp(pt_neg({PT(p)}))).toEqual("{enc(neg(p)).hex()}");\n'
    b += f'    expect(pt_eq({PT(p)}, {PT(p)})).toBeTrue();\n    expect(pt_eq({PT(p)}, {PT(q)})).toBeFalse();\n'
blk('P-256 point addition, negation, identity', b)
open(os.path.join(HERE, 'p256ops_test.resid'), 'w').write(out)

# ---- Shamir -----------------------------------------------------------
out = '// lib/shamir.resid against Python. Generated by gen_p256ops.py.\n\n' + head + '''UInt(256) sc256(Str hex) { return (UInt(256)) p256_from_be(cose_hex_decode(hex)); }
Str h256(UInt(256) x) { return hex_encode(sc_to_be((UInt(576)) x)); }

'''


def S2(n): return f'sc256("{n.to_bytes(32, "big").hex()}")'


def lagrange0(ids, i):
    r = 1
    for j in ids:
        if j != i: r = r * j * inv((j - i) % Q, Q) % Q
    return r


for case, (t, n) in enumerate([(1, 1), (2, 3), (3, 5), (4, 8), (2, 8), (8, 8)]):
    coeffs = [random.randrange(Q) for _ in range(t)]
    f = lambda x: sum(c * pow(x, j, Q) for j, c in enumerate(coeffs)) % Q
    shares = [f(i) for i in range(1, n + 1)]
    comm = [mul(c, G) for c in coeffs]
    cl = ', '.join(S2(c) for c in coeffs)
    b = f'    List(UInt(256)) c = [{cl}];\n'
    b += f'    List(UInt(256)) sh = sh_split(c, {n});\n    expect(sh.len()).toEqual({n});\n'
    for i, s in enumerate(shares):
        b += f'    expect(h256(sh[{i}])).toEqual("{s.to_bytes(32,"big").hex()}");\n'
    b += '    List(P256Aff) com = sh_commit(c);\n'
    for j, p in enumerate(comm):
        b += f'    expect(hp(com[{j}])).toEqual("{enc(p).hex()}");\n'
    for i in range(n):
        b += f'    expect(sh_verify(sh[{i}], {i+1}, com)).toBeTrue();\n'
        wrong = (shares[i] + 1) % Q
        b += f'    expect(sh_verify({S2(wrong)}, {i+1}, com)).toBeFalse();\n'
        if t > 1:  # a constant polynomial gives every id the same share
            b += f'    expect(sh_verify(sh[{i}], {(i+1) % n + 1 if n > 1 else 2}, com)).toBeFalse();\n'
    # reconstruction by several subsets of size t
    for _ in range(3):
        ids = sorted(random.sample(range(1, n + 1), t))
        sel = ', '.join(S2(shares[i - 1]) for i in ids)
        b += f'    expect(h256(sh_reconstruct({ids}, [{sel}]))).toEqual("{coeffs[0].to_bytes(32,"big").hex()}");\n'
        for i in ids:
            b += f'    expect(h256(sh_lagrange0({ids}, {i}))).toEqual("{lagrange0(ids, i).to_bytes(32,"big").hex()}");\n'
            b += f'    expect(h256(sh_to_additive({ids}, {i}, {S2(shares[i-1])}))).toEqual("{(lagrange0(ids, i) * shares[i-1] % Q).to_bytes(32,"big").hex()}");\n'
    # fewer than t shares do not give the secret (t >= 2)
    if t >= 2:
        ids = sorted(random.sample(range(1, n + 1), t - 1))
        sel = ', '.join(S2(shares[i - 1]) for i in ids)
        wrong = sum(lagrange0(ids, i) * shares[i - 1] for i in ids) % Q
        assert wrong != coeffs[0]
        b += f'    expect(h256(sh_reconstruct({ids}, [{sel}]))).toEqual("{wrong.to_bytes(32,"big").hex()}");\n'
    out += f'test "shamir {t}-of-{n}" {{\n{b}}}\n\n'
open(os.path.join(HERE, 'shamir_test.resid'), 'w').write(out)


# ---- lib/cggmp_curve.resid: compressed encodings and nat-typed operations
def comp(p):
    if p is None: return bytes(33)
    return bytes([2 + (p[1] & 1)]) + p[0].to_bytes(32, 'big')


out = '''// lib/cggmp_curve.resid against Python P-256: compressed encodings,
// decoding (including invalid inputs) and operations on natural numbers.
// Generated by gen_p256ops.py.

import "../../lib/cggmp_curve.resid";
import "../../lib/cose.resid";
import "../../lib/crypto.resid";

List(UInt(64)) nat(Str hex) { return bn_from_be(cose_hex_decode(hex)); }
Str hx(List(UInt(64)) x) { return hex_encode(bn_to_be(x, 32)); }
Str he(CvPt p) { return hex_encode(cv_enc(p)); }
CvPt pt(Str hex) { return match cv_dec(cose_hex_decode(hex)) { Some(p) => p, None => cv_inf() }; }
Bool valid(Str hex) { return match cv_dec(cose_hex_decode(hex)) { Some(_) => true, None => false }; }

'''
b = ''
for i in range(24):
    k = random.choice([1, 2, Q - 1, random.randrange(1, Q), random.randrange(1, Q)])
    p = mul(k, G)
    q = mul(random.randrange(1, Q), G)
    k2 = random.randrange(1, Q)
    b += f'    expect(he(pt("{comp(p).hex()}"))).toEqual("{comp(p).hex()}");\n'
    b += f'    expect(he(cv_mul_base(nat("{k.to_bytes(32,"big").hex()}")))).toEqual("{comp(mul(k, G)).hex()}");\n'
    b += f'    expect(he(cv_mul(nat("{k2.to_bytes(32,"big").hex()}"), pt("{comp(q).hex()}")))).toEqual("{comp(mul(k2, q)).hex()}");\n'
    b += f'    expect(he(cv_add(pt("{comp(p).hex()}"), pt("{comp(q).hex()}")))).toEqual("{comp(add(p, q)).hex()}");\n'
    b += f'    expect(he(cv_sub(pt("{comp(p).hex()}"), pt("{comp(p).hex()}")))).toEqual("{comp(None).hex()}");\n'
    b += f'    expect(he(cv_neg(pt("{comp(p).hex()}")))).toEqual("{comp(neg(p)).hex()}");\n'
    a, c = random.randrange(Q), random.randrange(1, Q)
    b += f'    expect(hx(sc_nat_add(nat("{a.to_bytes(32,"big").hex()}"), nat("{c.to_bytes(32,"big").hex()}")))).toEqual("{((a+c)%Q).to_bytes(32,"big").hex()}");\n'
    b += f'    expect(hx(sc_nat_mul(nat("{a.to_bytes(32,"big").hex()}"), nat("{c.to_bytes(32,"big").hex()}")))).toEqual("{((a*c)%Q).to_bytes(32,"big").hex()}");\n'
    b += f'    expect(hx(sc_nat_sub(nat("{a.to_bytes(32,"big").hex()}"), nat("{c.to_bytes(32,"big").hex()}")))).toEqual("{((a-c)%Q).to_bytes(32,"big").hex()}");\n'
    b += f'    expect(hx(sc_nat_inv(nat("{c.to_bytes(32,"big").hex()}")))).toEqual("{inv(c,Q).to_bytes(32,"big").hex()}");\n'
out += f'test "compressed points and scalar operations on naturals" {{\n{b}}}\n\n'
# invalid encodings
bad = [bytes(32) + b'\x00', b'\x04' + bytes(32), b'\x02' + (P).to_bytes(32, 'big'), b'\x05' + bytes(32)]
# an x with no point on the curve
while True:
    x = random.randrange(P)
    if pow((x**3 - 3 * x + 0x5ac635d8aa3a93e7b3ebbd55769886bc651d06b0cc53b0f63bce3c3e27d2604b) % P, (P - 1) // 2, P) != 1:
        bad.append(b'\x02' + x.to_bytes(32, 'big')); break
b = ''.join(f'    expect(valid("{x.hex()}")).toBeFalse();\n' for x in bad if x[0] != 0 or len(x) != 33)
b += f'    expect(valid("{bytes(33).hex()}")).toBeTrue();\n    expect(valid("02")).toBeFalse();\n'
out += f'test "invalid compressed points are refused, the identity encodes as zeros" {{\n{b}}}\n\n'
open(os.path.join(HERE, 'cggmp_curve_test.resid'), 'w').write(out)
